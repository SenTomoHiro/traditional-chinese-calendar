const 一分钟毫秒 = 60_000;

function 时间毫秒(时间: 北京时间): number {
  return Date.UTC(时间.年, 时间.月 - 1, 时间.日, 时间.时, 时间.分, 时间.秒);
}

function 毫秒时间(毫秒: number): 北京时间 {
  const 日期 = new Date(毫秒);
  return {
    年: 日期.getUTCFullYear(),
    月: 日期.getUTCMonth() + 1,
    日: 日期.getUTCDate(),
    时: 日期.getUTCHours(),
    分: 日期.getUTCMinutes(),
    秒: 日期.getUTCSeconds(),
  };
}

function 分钟取整(时间: 北京时间): 北京时间 {
  return 毫秒时间(Math.round(时间毫秒(时间) / 一分钟毫秒) * 一分钟毫秒);
}

function 当日零点(时间: 北京时间): 北京时间 {
  return { 年: 时间.年, 月: 时间.月, 日: 时间.日, 时: 0, 分: 0, 秒: 0 };
}

/** 复用既有真太阳时算法，数值反求指定真太阳时边界所对应的北京时间。 */
export function 反求北京时间(目标真太阳时: 北京时间, 经度: number): 北京时间 {
  const 目标毫秒 = 时间毫秒(目标真太阳时);
  let 下界 = 目标毫秒 - 26 * 60 * 60 * 1000;
  let 上界 = 目标毫秒 + 26 * 60 * 60 * 1000;

  for (let 次数 = 0; 次数 < 56 && 上界 - 下界 > 1000; 次数 += 1) {
    const 中点 = Math.floor((下界 + 上界) / 2000) * 1000;
    const 对应真太阳时 = 计算真太阳时(毫秒时间(中点), 经度).真太阳时;
    if (时间毫秒(对应真太阳时) < 目标毫秒) 下界 = 中点 + 1000;
    else 上界 = 中点;
  }
  return 毫秒时间(上界);
}

function 生成目标边界(最终时间: 北京时间): 北京时间[] {
  const 早子零点 = 最终时间.时 >= 23 ? 当日零点(平移时间(最终时间, 60 * 60)) : 当日零点(最终时间);
  return [
    平移时间(早子零点, -60 * 60),
    早子零点,
    ...Array.from({ length: 12 }, (_, 索引) => 平移时间(早子零点, (索引 * 2 + 1) * 60 * 60)),
  ];
}

export function 创建十二时辰概览(
  查询北京时间: 北京时间,
  时间依据: "北京时间" | "真太阳时",
  经度: number | null,
  配置: 时辰吉凶配置 | null,
  详细配置: 详细时辰配置 | null = null,
): 十二时辰概览 {
  const 实际依据 = 时间依据 === "真太阳时" && 经度 !== null ? "真太阳时" : "北京时间";
  const 最终时间 = 实际依据 === "真太阳时" ? 计算真太阳时(查询北京时间, 经度 as number).真太阳时 : 查询北京时间;
  const 目标边界 = 生成目标边界(最终时间);
  const 北京边界 = 目标边界.map((边界) => 分钟取整(实际依据 === "真太阳时" ? 反求北京时间(边界, 经度 as number) : 边界));
  const 分段时支: 时支[] = ["子", "子", ...地支.slice(1)] as 时支[];
  const 查询毫秒 = 时间毫秒(查询北京时间);

  const 时段 = 分段时支.map((当前时支, 索引): 时辰概览段 => {
    const 开始北京时间 = 北京边界[索引];
    const 下一边界 = 北京边界[索引 + 1];
    const 结束北京时间 = 平移时间(下一边界, -60);
    const 目标中点 = 平移时间(目标边界[索引], 索引 < 2 ? 30 * 60 : 60 * 60);
    const { 日柱, 日支 } = 计算日柱(目标中点);
    const 值神结果 = 计算时辰值神(配置, 日支, 当前时支);
    const 时柱 = 计算时柱(日柱, 当前时支);
    return {
      键: 索引 === 0 ? "夜子" : 索引 === 1 ? "早子" : 当前时支,
      名称: 索引 === 0 ? "夜子" : 索引 === 1 ? "早子" : `${当前时支}时`,
      时支: 当前时支,
      时间范围: `${格式化时分(开始北京时间)}～${格式化时分(结束北京时间)}`,
      开始北京时间,
      结束北京时间,
      日柱,
      时柱,
      值神: 值神结果.值神,
      吉凶: 值神结果.吉凶,
      详情: 计算详细时辰(详细配置, 日柱, 时柱, 值神结果.值神, 值神结果.吉凶),
      当前: 查询毫秒 >= 时间毫秒(开始北京时间) && 查询毫秒 < 时间毫秒(下一边界),
    };
  });

  return {
    时间依据: 实际依据,
    项目: [
      { 时支: "子", 名称: "子时", 时段: 时段.slice(0, 2), 当前: 时段.slice(0, 2).some((段) => 段.当前) },
      ...地支.slice(1).map((当前时支, 索引) => {
        const 当前段 = 时段[索引 + 2];
        return { 时支: 当前时支, 名称: `${当前时支}时`, 时段: [当前段], 当前: 当前段.当前 };
      }),
    ],
  };
}
