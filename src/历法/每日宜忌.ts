export const 每日宜忌规则口径 = "项目中文配置·节气月具体交接时刻" as const;

export interface 每日宜忌结果 {
  宜: string[];
  忌: string[];
  冲突: string[];
  命中条件: string[];
}

const 月级条件名称 = ["月建", "月破", "月厌", "月刑", "月害", "劫煞", "灾煞", "月煞"] as const;
type 月级条件 = (typeof 月级条件名称)[number];
type 地支名 = (typeof 地支)[number];

interface 日宜忌配置 {
  月级条件: Record<月建, Record<月级条件, 地支名>>;
  用事: 用事宜忌规则[];
}

function 解析日宜忌配置(文本 = 日宜忌配置文本): 日宜忌配置 {
  const 原始 = 解析配置("日宜忌.txt", 文本);
  if (原始.错误.length > 0) throw new Error(原始.错误.map((错误) => 错误.信息).join("；"));
  const 月级条件 = {} as Record<月建, Record<月级条件, 地支名>>;

  for (const 规则 of 原始.规则) {
    const 月匹配 = 规则.条件.match(/^([子丑寅卯辰巳午未申酉戌亥])月$/u);
    if (!月匹配) continue;
    const 条件 = {} as Record<月级条件, 地支名>;
    for (const 条目 of 规则.内容.split("、")) {
      const 匹配 = 条目.match(/^(月建|月破|月厌|月刑|月害|劫煞|灾煞|月煞)([子丑寅卯辰巳午未申酉戌亥])$/u);
      if (!匹配) throw new Error(`日宜忌配置无法识别“${条目}”`);
      条件[匹配[1] as 月级条件] = 匹配[2] as 地支名;
    }
    if (月级条件名称.some((名称) => !条件[名称])) throw new Error(`日宜忌缺少${月匹配[1]}月条件`);
    月级条件[月匹配[1] as 月建] = 条件;
  }

  const 用事配置结果 = 解析用事宜忌配置({
    ...原始,
    规则: 原始.规则.filter((规则) => /(?:宜|忌)$/u.test(规则.条件)),
  }, "日宜忌.txt");
  if (Object.keys(月级条件).length !== 12 || !用事配置结果.配置 || 用事配置结果.错误.length > 0) {
    throw new Error(["日宜忌配置不完整", ...用事配置结果.错误.map((错误) => 错误.信息)].join("；"));
  }
  return { 月级条件, 用事: 用事配置结果.配置 };
}

const 默认配置 = 解析日宜忌配置();
const 六合: Record<地支名, 地支名> = {
  子: "丑", 丑: "子", 寅: "亥", 亥: "寅", 卯: "戌", 戌: "卯",
  辰: "酉", 酉: "辰", 巳: "申", 申: "巳", 午: "未", 未: "午",
};
const 三合组: readonly (readonly 地支名[])[] = [
  ["寅", "午", "戌"], ["巳", "酉", "丑"], ["申", "子", "辰"], ["亥", "卯", "未"],
];
const 农历日条件: Record<number, string> = {
  1: "每月一日", 6: "每月六日", 12: "每月十二日", 15: "每月十五日",
  19: "每月十九日", 21: "每月二十一日", 23: "每月二十三日",
};

function 位于跨年节气区间(时间: 北京时间, 起点: 节气名称, 终点: 节气名称): boolean {
  const 本年起点 = 获取指定节气(时间.年, 起点);
  const 起点时刻 = 比较北京时间(时间, 本年起点) >= 0 ? 本年起点 : 获取指定节气(时间.年 - 1, 起点);
  return 比较北京时间(时间, 起点时刻) >= 0 && 比较北京时间(时间, 获取指定节气(起点时刻.年 + 1, 终点)) < 0;
}

function 计算命中条件(时间: 北京时间, 配置: 日宜忌配置): Set<string> {
  const 干支 = 计算干支(时间);
  const 日干 = 干支.日柱[0];
  const 日支 = 干支.日支;
  const 农历 = 转换为农历(时间);
  const 命中 = new Set<string>([`${计算值星(干支.月建, 日支)}日`, `${日干}日`, `${日支}日`]);

  for (const 名称 of 月级条件名称) {
    if (配置.月级条件[干支.月建][名称] === 日支) 命中.add(名称);
  }
  if (六合[干支.月建] === 日支) 命中.add("六合");
  const 月三合 = 三合组.find((组合) => 组合.includes(干支.月建));
  if (月三合?.includes(日支) && 日支 !== 干支.月建) 命中.add("三合");

  const 固定日条件 = 农历日条件[农历.日];
  if (固定日条件) 命中.add(固定日条件);
  if (农历.日 === 1) 命中.add("朔日");
  if (农历.日 === 15) 命中.add("望日");
  if ([7, 8, 22, 23].includes(农历.日)) 命中.add("弦日");

  if (位于跨年节气区间(时间, "立冬", "立春")) 命中.add("立冬后立春前");
  if (位于跨年节气区间(时间, "霜降", "立春")) 命中.add("霜降后立春前");
  const 雨水 = 获取指定节气(时间.年, "雨水");
  const 立夏 = 获取指定节气(时间.年, "立夏");
  if (比较北京时间(时间, 雨水) >= 0 && 比较北京时间(时间, 立夏) < 0) 命中.add("雨水后立夏前");
  return 命中;
}

/** 依据项目自主神煞与卷十一用事表；无明确制化依据的宜忌冲突不输出。 */
export function 计算每日宜忌(时间: 北京时间, 配置 = 默认配置): 每日宜忌结果 {
  const 命中条件 = 计算命中条件(时间, 配置);
  const 宜: string[] = [];
  const 忌: string[] = [];
  const 冲突: string[] = [];
  for (const 事项 of 配置.用事) {
    const 宜命中 = 事项.宜.some((条件) => 命中条件.has(条件));
    const 忌命中 = 事项.忌.some((条件) => 命中条件.has(条件));
    if (宜命中 && 忌命中) 冲突.push(事项.名称);
    else if (宜命中) 宜.push(事项.名称);
    else if (忌命中) 忌.push(事项.名称);
  }
  return { 宜, 忌, 冲突, 命中条件: [...命中条件] };
}

