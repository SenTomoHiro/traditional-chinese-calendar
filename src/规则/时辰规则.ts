import type { 配置解析结果, 配置规则 } from "./配置读取";
import type { 时支 } from "../历法/真太阳时";

export type 规则状态 = "命中" | "未命中" | "无规则" | "配置错误";

export interface 时辰规则判断 {
  名称: "杀师时" | "造葬杀风水师时" | "逐月杀风水师时";
  状态: 规则状态;
  说明: string;
}

const 农历月条件 = ["", "正月", "二月", "三月", "四月", "五月", "六月", "七月", "八月", "九月", "十月", "十一月", "十二月"];

function 查找配置(全部配置: 配置解析结果[], 文件名: string): 配置解析结果 | undefined {
  return 全部配置.find((配置) => 配置.文件名 === 文件名);
}

function 提取时支(规则: 配置规则): string[] {
  if (规则.内容 === "无") return [];
  return 规则.内容
    .split(/[、,，]/u)
    .map((内容) => 内容.trim().replace(/时$/u, ""))
    .filter(Boolean);
}

function 判断单项(
  全部配置: 配置解析结果[],
  名称: 时辰规则判断["名称"],
  文件名: string,
  条件: string,
  当前时支: 时支,
): 时辰规则判断 {
  const 配置 = 查找配置(全部配置, 文件名);
  if (!配置 || 配置.错误.length > 0) return { 名称, 状态: "配置错误", 说明: "配置未能正常读取" };
  const 规则 = 配置.规则.find((候选) => 候选.条件 === 条件);
  if (!规则) return { 名称, 状态: "配置错误", 说明: `缺少“${条件}”规则` };
  if (规则.内容 === "无") return { 名称, 状态: "无规则", 说明: `${条件} · 无此规则` };
  const 禁忌时支 = 提取时支(规则);
  const 命中 = 禁忌时支.includes(当前时支);
  return {
    名称,
    状态: 命中 ? "命中" : "未命中",
    说明: `${条件} · 忌${禁忌时支.join("、")}时 · ${当前时支}时${命中 ? "命中" : "未命中"}`,
  };
}

export function 判断全部时辰规则(
  全部配置: 配置解析结果[],
  日支: 时支,
  当前时支: 时支,
  农历月: number,
): 时辰规则判断[] {
  const 月条件 = 农历月条件[农历月];
  return [
    判断单项(全部配置, "杀师时", "杀师时.txt", `${日支}日`, 当前时支),
    判断单项(全部配置, "造葬杀风水师时", "造葬杀风水师时.txt", `${日支}日`, 当前时支),
    月条件
      ? 判断单项(全部配置, "逐月杀风水师时", "逐月杀风水师时.txt", 月条件, 当前时支)
      : { 名称: "逐月杀风水师时", 状态: "配置错误", 说明: "农历月份无效" },
  ];
}
