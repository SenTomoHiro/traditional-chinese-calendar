import 传统节日配置文本 from "../../配置/传统节日.txt?raw";
import { 天干, 计算日柱 } from "../历法/干支";
import type { 农历日期 } from "../历法/农历";
import { 获取指定节气 } from "../历法/节气";
import { 平移时间, 是同一公历日, type 北京时间 } from "../历法/时间";

export type 传统节日分类 = "常用传统节日" | "其他传统民俗节日";

export interface 传统节日配置项 {
  分类: 传统节日分类;
  月: number;
  日: number;
  名称: string[];
}

export interface 传统节日结果 {
  常用传统节日: string[];
  其他传统民俗节日: string[];
  全部: string[];
}

const 月份 = new Map([
  ["正月", 1], ["一月", 1], ["二月", 2], ["三月", 3], ["四月", 4], ["五月", 5], ["六月", 6],
  ["七月", 7], ["八月", 8], ["九月", 9], ["十月", 10], ["十一月", 11], ["冬月", 11],
  ["十二月", 12], ["腊月", 12],
]);

const 日期 = new Map([
  "初一", "初二", "初三", "初四", "初五", "初六", "初七", "初八", "初九", "初十",
  "十一", "十二", "十三", "十四", "十五", "十六", "十七", "十八", "十九", "二十",
  "廿一", "廿二", "廿三", "廿四", "廿五", "廿六", "廿七", "廿八", "廿九", "三十",
].map((名称, 索引) => [名称, 索引 + 1] as const));

export function 解析传统节日配置(文本 = 传统节日配置文本): 传统节日配置项[] {
  let 当前分类: 传统节日分类 | null = null;
  const 结果: 传统节日配置项[] = [];

  文本.split(/\r?\n/u).forEach((原文, 索引) => {
    const 行 = 原文.trim();
    if (行 === "# 常用传统节日") {
      当前分类 = "常用传统节日";
      return;
    }
    if (行 === "# 其他传统民俗节日") {
      当前分类 = "其他传统民俗节日";
      return;
    }
    if (!行 || 行.startsWith("#")) return;
    if (!当前分类) throw new Error(`传统节日.txt 第 ${索引 + 1} 行缺少分类标题`);

    const 匹配 = 行.match(/^((?:正|一|二|三|四|五|六|七|八|九|十|十一|十二|冬|腊)月)(初一|初二|初三|初四|初五|初六|初七|初八|初九|初十|十一|十二|十三|十四|十五|十六|十七|十八|十九|二十|廿一|廿二|廿三|廿四|廿五|廿六|廿七|廿八|廿九|三十)[：:](.+)$/u);
    if (!匹配) throw new Error(`传统节日.txt 第 ${索引 + 1} 行格式无法识别：${行}`);
    const 月 = 月份.get(匹配[1]);
    const 日 = 日期.get(匹配[2]);
    const 名称 = 匹配[3].split(/[、，,]/u).map((项目) => 项目.trim()).filter(Boolean);
    if (!月 || !日 || 名称.length === 0) throw new Error(`传统节日.txt 第 ${索引 + 1} 行内容不完整：${行}`);
    结果.push({ 分类: 当前分类, 月, 日, 名称 });
  });

  return 结果;
}

const 固定节日 = 解析传统节日配置();

function 是目标公历日(当前: 北京时间, 目标: 北京时间): boolean {
  return 是同一公历日(当前, 目标);
}

function 第五个戊日(节气: 北京时间): 北京时间 {
  const 日干 = 计算日柱(节气).日柱[0];
  let 首个戊日偏移 = 天干.indexOf("戊") - 天干.indexOf(日干 as (typeof 天干)[number]);
  if (首个戊日偏移 < 0) 首个戊日偏移 += 10;
  return 平移时间(节气, (首个戊日偏移 + 40) * 86_400);
}

/**
 * 复刻 lunar-typescript 1.8.6 的传统节日结果与顺序。
 * 社日只替换日干来源，统一使用本项目 00:00 换日的日柱算法。
 */
export function 计算传统节日(
  时间: 北京时间,
  农历: 农历日期,
  下一日农历: 农历日期,
): 传统节日结果 {
  const 常用传统节日: string[] = [];
  const 其他传统民俗节日: string[] = [];

  if (!农历.是否闰月) {
    for (const 项目 of 固定节日) {
      if (项目.月 !== 农历.月 || 项目.日 !== 农历.日) continue;
      const 容器 = 项目.分类 === "常用传统节日" ? 常用传统节日 : 其他传统民俗节日;
      容器.push(...项目.名称);
    }
  }

  // 上游 1.8.6 使用绝对十二月，并以次日进入新农历年识别大小月除夕。
  if (农历.月 === 12 && 农历.日 >= 29 && 农历.年 !== 下一日农历.年) {
    常用传统节日.push("除夕");
  }

  const 清明 = 获取指定节气(时间.年, "清明");
  if (是目标公历日(时间, 平移时间(清明, -86_400))) 其他传统民俗节日.push("寒食节");
  if (是目标公历日(时间, 第五个戊日(获取指定节气(时间.年, "立春")))) {
    其他传统民俗节日.push("春社");
  }
  if (是目标公历日(时间, 第五个戊日(获取指定节气(时间.年, "立秋")))) {
    其他传统民俗节日.push("秋社");
  }

  return {
    常用传统节日,
    其他传统民俗节日,
    全部: [...new Set([...常用传统节日, ...其他传统民俗节日])],
  };
}
