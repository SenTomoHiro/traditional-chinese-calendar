import { 计算干支 } from "../历法/干支";
import { 转换为农历 } from "../历法/农历";
import { 获取年度节气 } from "../历法/节气";
import { 比较北京时间, type 北京时间 } from "../历法/时间";
import type { 配置解析结果, 配置规则 } from "./配置读取";

export type 日级风水规则名称 =
  | "年罗睺日"
  | "季罗睺日"
  | "月罗睺日"
  | "阴阳宅禁日"
  | "逐年杀风水师日"
  | "逐月杀风水师日";
export type 风水犯忌层级 = "年" | "季" | "月" | "日";
export type 日级风水状态 = "命中" | "未命中" | "配置错误";

export interface 日级风水判断 {
  名称: 日级风水规则名称;
  层级: 风水犯忌层级;
  状态: 日级风水状态;
  说明: string;
  方位?: string;
}

export interface 日级风水禁忌结果 {
  规则: 日级风水判断[];
  命中: 日级风水判断[];
  犯忌层级: 风水犯忌层级[];
  当日状态: string;
}

const 农历月条件 = ["", "正月", "二月", "三月", "四月", "五月", "六月", "七月", "八月", "九月", "十月", "十一月", "十二月"];
const 四季节气: Readonly<Record<"立春" | "立夏" | "立秋" | "立冬", string>> = {
  立春: "春季",
  立夏: "夏季",
  立秋: "秋季",
  立冬: "冬季",
};
const 层级顺序: 风水犯忌层级[] = ["年", "季", "月", "日"];

function 查找配置(全部配置: 配置解析结果[], 文件名: string): 配置解析结果 | undefined {
  return 全部配置.find((配置) => 配置.文件名 === 文件名);
}

function 查找规则(全部配置: 配置解析结果[], 文件名: string, 条件: string): 配置规则 | null {
  const 配置 = 查找配置(全部配置, 文件名);
  if (!配置 || 配置.错误.length > 0) return null;
  return 配置.规则.find((规则) => 规则.条件 === 条件) ?? null;
}

function 配置有效(全部配置: 配置解析结果[], 文件名: string): boolean {
  const 配置 = 查找配置(全部配置, 文件名);
  return Boolean(配置 && 配置.错误.length === 0);
}

function 配置错误(名称: 日级风水规则名称, 层级: 风水犯忌层级): 日级风水判断 {
  return { 名称, 层级, 状态: "配置错误", 说明: "配置未能正常读取" };
}

function 判断目标(
  名称: 日级风水规则名称,
  层级: 风水犯忌层级,
  规则: 配置规则 | null,
  实际值: string,
): 日级风水判断 {
  if (!规则) return 配置错误(名称, 层级);
  const 命中 = 规则.内容 === 实际值;
  return { 名称, 层级, 状态: 命中 ? "命中" : "未命中", 说明: `${规则.内容}${命中 ? "命中" : "未命中"}` };
}

export function 获取罗睺季节(时间: 北京时间): "春季" | "夏季" | "秋季" | "冬季" {
  const 最近边界 = [时间.年 - 1, 时间.年]
    .flatMap(获取年度节气)
    .filter((节气) => Object.hasOwn(四季节气, 节气.名称))
    .filter((节气) => 比较北京时间(节气, 时间) <= 0)
    .sort((左, 右) => 比较北京时间(右, 左))[0];
  if (!最近边界) throw new Error("无法确定罗睺季节");
  return 四季节气[最近边界.名称 as keyof typeof 四季节气] as "春季" | "夏季" | "秋季" | "冬季";
}

export function 汇总当日风水状态(规则: 日级风水判断[]): Pick<日级风水禁忌结果, "命中" | "犯忌层级" | "当日状态"> {
  const 命中 = 规则.filter((条目) => 条目.状态 === "命中");
  const 犯忌层级 = 层级顺序.filter((层级) => 命中.some((条目) => 条目.层级 === 层级));
  const 有配置错误 = 规则.some((条目) => 条目.状态 === "配置错误");
  const 命中名称 = [...new Set(命中.map((条目) => 条目.名称))];
  return {
    命中,
    犯忌层级,
    当日状态: 有配置错误 ? "规则配置异常" : 命中名称.length === 0 ? "当日宜" : 命中名称.join(" · "),
  };
}

export function 计算日级风水禁忌(全部配置: 配置解析结果[], 时间: 北京时间): 日级风水禁忌结果 {
  const 农历 = 转换为农历(时间);
  const { 年柱, 日柱 } = 计算干支(时间);
  const 年条件 = `${年柱[1]}年`;
  const 月条件 = 农历月条件[农历.月];
  const 日支条件 = `${日柱[1]}日`;
  const 季节条件 = 获取罗睺季节(时间);

  const 年罗睺 = 判断目标("年罗睺日", "年", 查找规则(全部配置, "年罗睺日.txt", 年条件), `${日柱}日`);
  const 季罗睺 = 判断目标("季罗睺日", "季", 查找规则(全部配置, "季罗睺日.txt", 季节条件), `${日柱}日`);
  const 月罗睺 = 判断目标("月罗睺日", "月", 查找规则(全部配置, "月罗睺日.txt", 月条件), 日支条件);

  const 阴阳宅文件 = "阴阳宅禁日.txt";
  const 阴阳宅条件 = `${月条件}${农历.日名}`;
  const 阴阳宅配置正常 = 配置有效(全部配置, 阴阳宅文件);
  const 阴阳宅命中 = 阴阳宅配置正常 && Boolean(查找规则(全部配置, 阴阳宅文件, 阴阳宅条件));
  const 阴阳宅: 日级风水判断 = 阴阳宅配置正常
    ? { 名称: "阴阳宅禁日", 层级: "日", 状态: 阴阳宅命中 ? "命中" : "未命中", 说明: `${阴阳宅条件}${阴阳宅命中 ? "命中" : "未命中"}` }
    : 配置错误("阴阳宅禁日", "日");

  const 逐年规则 = 查找规则(全部配置, "逐年杀风水师日.txt", 年条件);
  const [逐年日期 = "", 逐年方位 = ""] = 逐年规则?.内容.split(/[；;]/u).map((内容) => 内容.trim()) ?? [];
  const 逐年命中 = Boolean(逐年规则) && 逐年日期 === `${日柱}日`;
  const 逐年: 日级风水判断 = 逐年规则
    ? {
        名称: "逐年杀风水师日",
        层级: "年",
        状态: 逐年命中 ? "命中" : "未命中",
        说明: `${逐年日期}${逐年命中 ? "命中" : "未命中"}`,
        ...(逐年命中 && 逐年方位 ? { 方位: 逐年方位 } : {}),
      }
    : 配置错误("逐年杀风水师日", "年");

  const 逐月 = 判断目标("逐月杀风水师日", "月", 查找规则(全部配置, "逐月杀风水师日.txt", 月条件), 日支条件);
  const 规则 = [年罗睺, 季罗睺, 月罗睺, 阴阳宅, 逐年, 逐月];
  return { 规则, ...汇总当日风水状态(规则) };
}
