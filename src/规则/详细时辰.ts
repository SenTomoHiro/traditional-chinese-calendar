function 列表(内容: string): string[] {
  if (内容 === "无") return [];
  return 内容.split(/[、,，]/u).map((值) => 值.trim()).filter(Boolean);
}

function 错误项(文件名: string, 规则: 配置规则 | null, 信息: string): 配置错误 {
  return { 文件名, 行号: 规则?.行号 ?? 0, 原文: 规则?.原文 ?? "", 信息 };
}

function 空干映射(): Record<天干名, 地支名[]> {
  return 天干.reduce((映射, 干) => {
    映射[干] = [];
    return 映射;
  }, {} as Record<天干名, 地支名[]>);
}

function 空支映射(): Record<地支名, 地支名[]> {
  return 地支.reduce((映射, 支) => {
    映射[支] = [];
    return 映射;
  }, {} as Record<地支名, 地支名[]>);
}

function 解析五不遇(规则: 配置规则 | undefined, 错误: 配置错误[]): Record<天干名, string> {
  const 结果 = 天干.reduce((映射, 干) => {
    映射[干] = "";
    return 映射;
  }, {} as Record<天干名, string>);
  if (!规则) return 结果;

  for (const 条目 of 列表(规则.内容)) {
    const 匹配 = 条目.match(/^([甲乙丙丁戊己庚辛壬癸])日([甲乙丙丁戊己庚辛壬癸][子丑寅卯辰巳午未申酉戌亥])时$/u);
    if (!匹配) {
      错误.push(错误项("时辰神煞.txt", 规则, `无法识别五不遇定局“${条目}”`));
      continue;
    }
    const 日干 = 匹配[1] as 天干名;
    if (结果[日干]) 错误.push(错误项("时辰神煞.txt", 规则, `“${日干}日”重复配置五不遇`));
    结果[日干] = 匹配[2];
  }
  const 缺少 = 天干.filter((干) => !结果[干]);
  if (缺少.length > 0) 错误.push(错误项("时辰神煞.txt", 规则, `五不遇缺少${缺少.join("、")}日定局`));
  return 结果;
}

function 解析支列表(规则: 配置规则, 错误: 配置错误[]): 地支名[] {
  const 结果 = 列表(规则.内容).map((值) => 值.replace(/时$/u, ""));
  if (结果.some((值) => !地支.includes(值 as 地支名)) || new Set(结果).size !== 结果.length) {
    错误.push(错误项("时辰神煞.txt", 规则, "时支列表包含无效或重复内容"));
    return [];
  }
  return 结果 as 地支名[];
}

function 解析对组(规则: 配置规则, 有方向: boolean, 错误: 配置错误[]): Set<string> {
  const 结果 = new Set<string>();
  for (const 条目 of 列表(规则.内容)) {
    const 匹配 = 有方向 ? 条目.match(/^([子丑寅卯辰巳午未申酉戌亥])刑([子丑寅卯辰巳午未申酉戌亥])$/u) : 条目.match(/^([子丑寅卯辰巳午未申酉戌亥])([子丑寅卯辰巳午未申酉戌亥])$/u);
    if (!匹配) {
      错误.push(错误项("时辰神煞.txt", 规则, `无法识别“${条目}”`));
      continue;
    }
    const 键 = 有方向 ? `${匹配[1]}${匹配[2]}` : [匹配[1], 匹配[2]].sort().join("");
    if (结果.has(键)) 错误.push(错误项("时辰神煞.txt", 规则, `“${条目}”重复配置`));
    结果.add(键);
  }
  return 结果;
}

function 写入干映射(
  映射: Record<天干名, 地支名[]>,
  日干文本: string,
  时支列表: 地支名[],
  规则: 配置规则,
  错误: 配置错误[],
): void {
  const 日干列表 = [...日干文本] as 天干名[];
  if (日干列表.length === 0 || 日干列表.some((干) => !天干.includes(干))) {
    错误.push(错误项("时辰神煞.txt", 规则, "日干条件无效"));
    return;
  }
  for (const 日干 of 日干列表) {
    if (映射[日干].length > 0) 错误.push(错误项("时辰神煞.txt", 规则, `“${日干}日”重复配置`));
    映射[日干] = 时支列表;
  }
}

function 解析神煞配置(结果: 配置解析结果 | undefined): { 配置: 时辰神煞配置 | null; 错误: 配置错误[] } {
  if (!结果) return { 配置: null, 错误: [错误项("时辰神煞.txt", null, "缺少配置文件")] };
  const 错误 = [...结果.错误];
  const 原文串 = 结果.规则.map((规则) => 规则.原文).join("\n");
  if (/[戍]/u.test(原文串)) 错误.push(错误项("时辰神煞.txt", null, "发现地支“戍”，应为“戌”"));
  if (/[已]/u.test(原文串)) 错误.push(错误项("时辰神煞.txt", null, "发现天干“已”，应为“己”"));

  const 固定规则 = (名称: string): 配置规则 | undefined => {
    const 匹配 = 结果.规则.filter((规则) => 规则.条件 === 名称);
    if (匹配.length !== 1) 错误.push(错误项("时辰神煞.txt", 匹配[1] ?? null, `“${名称}”必须且只能配置一次`));
    return 匹配[0];
  };
  const 六冲规则 = 固定规则("六冲");
  const 六合规则 = 固定规则("六合");
  const 六害规则 = 固定规则("六害");
  const 相刑规则 = 固定规则("相刑");
  const 自刑规则 = 固定规则("自刑");
  const 五不遇规则 = 固定规则("五不遇");
  const 五不遇 = 解析五不遇(五不遇规则, 错误);

  const 天乙贵人 = 空干映射();
  const 天官贵人 = 空干映射();
  const 福星贵人 = 空干映射();
  const 喜神 = 空干映射();
  const 日禄 = 空干映射();
  const 日马 = 空支映射();
  const 路空 = 空干映射();
  const 旬空: Record<string, 地支名[]> = {};
  const 已识别 = new Set(["六冲", "六合", "六害", "相刑", "自刑", "五不遇"]);

  for (const 规则 of 结果.规则) {
    if (已识别.has(规则.条件)) continue;
    const 匹配 = 规则.条件.match(/^(天乙贵人|天官贵人|福星贵人|喜神|日禄|路空)·([甲乙丙丁戊己庚辛壬癸]+)日$/u);
    if (匹配) {
      const 映射表 = { 天乙贵人, 天官贵人, 福星贵人, 喜神, 日禄, 路空 };
      const 映射 = 映射表[匹配[1] as keyof typeof 映射表];
      写入干映射(映射, 匹配[2], 解析支列表(规则, 错误), 规则, 错误);
      continue;
    }
    const 日马匹配 = 规则.条件.match(/^日马·([子丑寅卯辰巳午未申酉戌亥]+)日$/u);
    if (日马匹配) {
      for (const 日支 of [...日马匹配[1]] as 地支名[]) {
        if (日马[日支].length > 0) 错误.push(错误项("时辰神煞.txt", 规则, `“${日支}日”重复配置日马`));
        日马[日支] = 解析支列表(规则, 错误);
      }
      continue;
    }
    const 旬空匹配 = 规则.条件.match(/^旬空·(甲[子戌申午辰寅])旬$/u);
    if (旬空匹配) {
      if (旬空[旬空匹配[1]]) 错误.push(错误项("时辰神煞.txt", 规则, `“${旬空匹配[1]}旬”重复配置`));
      旬空[旬空匹配[1]] = 解析支列表(规则, 错误);
      continue;
    }
    错误.push(错误项("时辰神煞.txt", 规则, `未知规则“${规则.条件}”`));
  }

  for (const [名称, 映射] of Object.entries({ 天乙贵人, 天官贵人, 福星贵人, 喜神, 日禄, 路空 })) {
    const 缺少 = 天干.filter((干) => 映射[干].length === 0);
    if (缺少.length > 0) 错误.push(错误项("时辰神煞.txt", null, `${名称}缺少${缺少.join("、")}日`));
  }
  const 缺少日马 = 地支.filter((支) => 日马[支].length === 0);
  if (缺少日马.length > 0) 错误.push(错误项("时辰神煞.txt", null, `日马缺少${缺少日马.join("、")}日`));
  const 旬首 = ["甲子", "甲戌", "甲申", "甲午", "甲辰", "甲寅"];
  if (旬首.some((旬) => !旬空[旬])) 错误.push(错误项("时辰神煞.txt", null, "旬空必须完整配置六旬"));

  if (错误.length > 0 || !六冲规则 || !六合规则 || !六害规则 || !相刑规则 || !自刑规则) return { 配置: null, 错误 };
  const 自刑 = new Set(解析支列表({ ...自刑规则, 内容: 自刑规则.内容.split(/[、,，]/u).map((值) => `${值}时`).join("、") }, 错误));
  return {
    配置: {
      六冲: 解析对组(六冲规则, false, 错误),
      六合: 解析对组(六合规则, false, 错误),
      六害: 解析对组(六害规则, false, 错误),
      相刑: 解析对组(相刑规则, true, 错误),
      自刑,
      天乙贵人,
      天官贵人,
      福星贵人,
      喜神,
      日禄,
      日马,
      旬空,
      路空,
      五不遇,
    },
    错误,
  };
}

function 解析宜忌配置(结果: 配置解析结果 | undefined): { 配置: 用事宜忌规则[] | null; 错误: 配置错误[] } {
  if (!结果) return { 配置: null, 错误: [错误项("时辰宜忌.txt", null, "缺少配置文件")] };
  const 错误 = [...结果.错误];
  const 暂存 = new Map<string, { 宜?: string[]; 忌?: string[] }>();
  for (const 规则 of 结果.规则) {
    if (规则.原文.includes("戍")) 错误.push(错误项("时辰宜忌.txt", 规则, "发现地支“戍”，应为“戌”"));
    if (规则.原文.includes("已日")) 错误.push(错误项("时辰宜忌.txt", 规则, "发现天干“已”，应为“己”"));
    const 匹配 = 规则.条件.match(/^(.+?)(宜|忌)$/u);
    if (!匹配) {
      错误.push(错误项("时辰宜忌.txt", 规则, "事项必须以“宜”或“忌”结尾"));
      continue;
    }
    const 名称 = 匹配[1];
    const 类型 = 匹配[2] as "宜" | "忌";
    const 内容 = 列表(规则.内容);
    if (new Set(内容).size !== 内容.length) 错误.push(错误项("时辰宜忌.txt", 规则, `“${名称}${类型}”存在重复条件`));
    const 未知 = 内容.filter((条件) => !宜忌已知条件.has(条件));
    if (未知.length > 0) 错误.push(错误项("时辰宜忌.txt", 规则, `未知条件：${未知.join("、")}`));
    const 条目 = 暂存.get(名称) ?? {};
    if (条目[类型]) 错误.push(错误项("时辰宜忌.txt", 规则, `“${名称}${类型}”重复配置`));
    条目[类型] = 内容;
    暂存.set(名称, 条目);
  }

  for (const [名称, 条目] of 暂存) {
    if (!条目.宜 || !条目.忌) 错误.push(错误项("时辰宜忌.txt", null, `“${名称}”必须同时配置宜、忌，允许内容写“无”`));
    const 重叠 = (条目.宜 ?? []).filter((条件) => (条目.忌 ?? []).includes(条件));
    if (重叠.length > 0) 错误.push(错误项("时辰宜忌.txt", null, `“${名称}”宜忌重复：${重叠.join("、")}`));
  }
  if (暂存.size < 60) 错误.push(错误项("时辰宜忌.txt", null, `通书六十事配置不足，当前仅${暂存.size}项`));
  if (错误.length > 0) return { 配置: null, 错误 };
  return {
    配置: [...暂存].map(([名称, 条目]) => ({ 名称, 宜: 条目.宜 ?? [], 忌: 条目.忌 ?? [] })),
    错误: [],
  };
}

export function 解析详细时辰配置(配置结果: 配置解析结果[]): 详细时辰配置解析结果 {
  const 神煞 = 解析神煞配置(配置结果.find((配置) => 配置.文件名 === "时辰神煞.txt"));
  const 宜忌 = 解析宜忌配置(配置结果.find((配置) => 配置.文件名 === "时辰宜忌.txt"));
  const 错误 = [...神煞.错误, ...宜忌.错误];
  if (!神煞.配置 || !宜忌.配置 || 错误.length > 0) return { 配置: null, 错误 };
  return { 配置: { 神煞: 神煞.配置, 用事: 宜忌.配置 }, 错误: [] };
}

function 配对键(甲: string, 乙: string): string {
  return [甲, 乙].sort().join("");
}

function 旬首(日柱: string): string | null {
  const 干索引 = 天干.indexOf(日柱[0] as 天干名);
  const 支索引 = 地支.indexOf(日柱[1] as 地支名);
  if (干索引 < 0 || 支索引 < 0) return null;
  const 干支表 = Array.from({ length: 60 }, (_, 索引) => `${天干[索引 % 10]}${地支[索引 % 12]}`);
  const 日序 = 干支表.indexOf(日柱);
  return 日序 < 0 ? null : 干支表[Math.floor(日序 / 10) * 10];
}

function 生成用事宜忌(配置: 用事宜忌规则[], 日时关系: string[], 吉神: string[], 凶煞: string[]) {
  void 日时关系;
  void 吉神;
  // 卷十一列的是日级用事宜忌，不能把时辰“日建、日合、日马”
  // 直接改名为日级“建日、六合、驿马”。这里只采用《用时法》
  // 明确落到时辰层级的旬空、路空出行限制；其余事项等待完整日期环境。
  const 命中条件 = new Set<string>(凶煞.filter((名称) => 名称 === "旬空" || 名称 === "路空"));
  const 时宜: string[] = [];
  const 时忌: string[] = [];
  const 冲突: string[] = [];
  const 未判定用事: string[] = [];

  for (const 事项 of 配置) {
    const 宜命中 = 事项.宜.some((条件) => 命中条件.has(条件));
    const 忌命中 = 事项.忌.some((条件) => 命中条件.has(条件));
    if (宜命中 && 忌命中) {
      冲突.push(事项.名称);
      未判定用事.push(事项.名称);
    } else if (宜命中) {
      时宜.push(事项.名称);
    } else if (忌命中) {
      时忌.push(事项.名称);
    } else {
      未判定用事.push(事项.名称);
    }
  }
  return { 时宜, 时忌, 冲突, 未判定用事 };
}

export function 计算详细时辰(
  配置: 详细时辰配置 | null,
  日柱: string,
  时柱: string,
  值神: 时辰值神 | "配置错误",
  基础吉凶: 时辰吉凶 | "—",
): 详细时辰结果 {
  const 空结果: 详细时辰结果 = {
    日时关系: [], 吉神: [], 凶煞: [], 时宜: [], 时忌: [], 冲突: [], 未判定用事: [], 依据: "详细规则配置不可用",
  };
  if (!配置) return 空结果;
  const 日干 = 日柱[0] as 天干名;
  const 日支 = 日柱[1] as 地支名;
  const 时干 = 时柱[0] as 天干名;
  const 时支 = 时柱[1] as 时支;
  if (!天干.includes(日干) || !地支.includes(日支) || !天干.includes(时干) || !地支.includes(时支)) return 空结果;

  const 神煞 = 配置.神煞;
  const 日时关系: 详细时辰结果["日时关系"] = [];
  if (日支 === 时支) 日时关系.push("日建");
  if (神煞.六冲.has(配对键(日支, 时支))) 日时关系.push("日破");
  if (神煞.六合.has(配对键(日支, 时支))) 日时关系.push("日合");
  if (神煞.六害.has(配对键(日支, 时支))) 日时关系.push("日害");
  if (神煞.相刑.has(`${日支}${时支}`) || (日支 === 时支 && 神煞.自刑.has(日支))) 日时关系.push("日刑");

  const 吉神: 详细时辰结果["吉神"] = [];
  for (const 名称 of 详细时辰吉神名称) {
    const 映射 = 名称 === "日马" ? 神煞.日马[日支] : 神煞[名称][日干];
    if (映射.includes(时支)) 吉神.push(名称);
  }

  const 凶煞: 详细时辰结果["凶煞"] = [];
  if (神煞.五不遇[日干] === 时柱) 凶煞.push("五不遇");
  const 当前旬首 = 旬首(日柱);
  if (当前旬首 && 神煞.旬空[当前旬首]?.includes(时支)) 凶煞.push("旬空");
  if (神煞.路空[日干].includes(时支)) 凶煞.push("路空");

  const 宜忌 = 生成用事宜忌(配置.用事, 日时关系, 吉神, 凶煞);

  const 依据卷 = 值神 === "配置错误" || 基础吉凶 === "—"
    ? "《钦定协纪辨方书》卷七、卷十一、卷三十二"
    : "《玉匣记·诸日起吉时歌》；《钦定协纪辨方书》卷七、卷十一、卷三十二";
  return { 日时关系, 吉神, 凶煞, ...宜忌, 依据: 依据卷 };
}
