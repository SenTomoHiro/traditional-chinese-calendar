import { 格式化四柱, 计算历法 } from "./历法";
import { 格式化日期时间, type 北京时间 } from "./历法/时间";
import { 计算最终时间 } from "./历法/真太阳时";
import type { 时间依据 } from "./当前历时";

/** 依赖对更广年份也能计算，但未公布稳定边界；页面只开放已完整回归的实用范围。 */
export const 八字支持范围 = {
  最小日期: "1900-01-01",
  最大日期: "2100-12-31",
} as const;

export interface 生辰八字结果 {
  输入北京时间: 北京时间;
  最终时间: 北京时间;
  时间依据: 时间依据;
  经度: number | null;
  年柱: string;
  月柱: string;
  日柱: string;
  时柱: string;
  四柱: string;
  八字: string;
}

export type 生辰八字查询结果 =
  | { 成功: true; 结果: 生辰八字结果 }
  | { 成功: false; 提示: string };

function 解析输入时间(日期文本: string, 时间文本: string): 北京时间 | null {
  const 日期 = 日期文本.match(/^(\d{4})-(\d{2})-(\d{2})$/u);
  const 时间 = 时间文本.match(/^(\d{2}):(\d{2})$/u);
  if (!日期 || !时间) return null;
  const [年, 月, 日, 时, 分] = [日期[1], 日期[2], 日期[3], 时间[1], 时间[2]].map(Number);
  const 校验 = new Date(Date.UTC(年, 月 - 1, 日, 时, 分));
  if (
    校验.getUTCFullYear() !== 年 ||
    校验.getUTCMonth() + 1 !== 月 ||
    校验.getUTCDate() !== 日 ||
    校验.getUTCHours() !== 时 ||
    校验.getUTCMinutes() !== 分
  ) return null;
  return { 年, 月, 日, 时, 分, 秒: 0 };
}

export function 计算生辰八字(
  输入北京时间: 北京时间,
  时间依据: 时间依据,
  经度: number | null,
): 生辰八字结果 {
  if (时间依据 === "真太阳时" && 经度 === null) throw new Error("真太阳时查询缺少出生地经度");
  const 最终 = 计算最终时间(输入北京时间, 时间依据 === "真太阳时" ? 经度 : null);
  const 历法 = 计算历法(最终.最终时间);
  const 四柱 = 格式化四柱({
    年柱: 历法.年柱,
    月柱: 历法.月柱,
    日柱: 历法.日柱,
    时柱: 最终.时柱,
  });
  return {
    输入北京时间,
    最终时间: 最终.最终时间,
    时间依据,
    经度: 时间依据 === "真太阳时" ? 经度 : null,
    年柱: 历法.年柱,
    月柱: 历法.月柱,
    日柱: 历法.日柱,
    时柱: 最终.时柱,
    四柱,
    八字: `${历法.年柱}　${历法.月柱}　${历法.日柱}　${最终.时柱}`,
  };
}

export function 查询生辰八字(
  日期文本: string,
  时间文本: string,
  时间依据: 时间依据,
  经度: number | null,
): 生辰八字查询结果 {
  if (日期文本 < 八字支持范围.最小日期 || 日期文本 > 八字支持范围.最大日期) {
    return { 成功: false, 提示: `当前历法计算支持范围为 ${八字支持范围.最小日期} 至 ${八字支持范围.最大日期}` };
  }
  const 输入 = 解析输入时间(日期文本, 时间文本);
  if (!输入) return { 成功: false, 提示: "请输入有效的公历日期和时间" };
  if (时间依据 === "真太阳时" && 经度 === null) {
    return { 成功: false, 提示: "请输入出生地经度，或使用当前定位" };
  }
  try {
    return { 成功: true, 结果: 计算生辰八字(输入, 时间依据, 经度) };
  } catch {
    return { 成功: false, 提示: `当前历法计算支持范围为 ${八字支持范围.最小日期} 至 ${八字支持范围.最大日期}` };
  }
}

export function 生辰八字时间说明(结果: 生辰八字结果): string[] {
  if (结果.时间依据 === "北京时间") return [`输入北京时间：${格式化日期时间(结果.输入北京时间)}`];
  return [
    `输入北京时间：${格式化日期时间(结果.输入北京时间)}`,
    `出生地经度：${结果.经度?.toFixed(2)}°E`,
    `真太阳时：${格式化日期时间(结果.最终时间)}`,
  ];
}
