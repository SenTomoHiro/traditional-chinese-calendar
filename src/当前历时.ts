import type { 配置解析结果 } from "./规则/配置读取";
import { 判断全部时辰规则 } from "./规则/时辰规则";
import { 解析时辰吉凶配置, type 时辰吉凶配置 } from "./规则/时辰吉凶";
import { 解析详细时辰配置, type 详细时辰配置 } from "./规则/详细时辰";
import type { 配置错误 } from "./规则/配置读取";
import { 格式化四柱, 计算最终时间, 计算历法, 计算真太阳时 } from "./历法";
import { 创建十二时辰概览 } from "./历法/十二时辰";
import type { 北京时间 } from "./历法/时间";

export type 时间依据 = "北京时间" | "真太阳时";

export interface 已解析时辰配置 {
  时辰吉凶: 时辰吉凶配置 | null;
  详细时辰: 详细时辰配置 | null;
  错误: 配置错误[];
}

export function 初始化时辰配置(配置结果: 配置解析结果[]): 已解析时辰配置 {
  const 时辰吉凶 = 解析时辰吉凶配置(配置结果.find((配置) => 配置.文件名 === "时辰吉凶.txt"));
  const 详细时辰 = 解析详细时辰配置(配置结果);
  return {
    时辰吉凶: 时辰吉凶.配置,
    详细时辰: 详细时辰.配置,
    错误: [...时辰吉凶.错误, ...详细时辰.错误],
  };
}

export function 计算当前历时(
  北京时间: 北京时间,
  请求时间依据: 时间依据,
  经度: number | null,
  配置结果: 配置解析结果[],
  已解析配置 = 初始化时辰配置(配置结果),
) {
  const 时间依据: 时间依据 = 请求时间依据 === "真太阳时" && 经度 !== null ? "真太阳时" : "北京时间";
  const 真太阳时结果 = 经度 === null ? null : 计算真太阳时(北京时间, 经度);
  const 最终 = 计算最终时间(北京时间, 时间依据 === "真太阳时" ? 经度 : null);
  const 历法结果 = 计算历法(最终.最终时间);
  const 四柱 = 格式化四柱({
    年柱: 历法结果.年柱,
    月柱: 历法结果.月柱,
    日柱: 历法结果.日柱,
    时柱: 最终.时柱,
  });
  const 十二时辰 = 创建十二时辰概览(
    北京时间,
    时间依据,
    经度,
    已解析配置.时辰吉凶,
    已解析配置.详细时辰,
    配置结果,
  );
  const 当前时段规则 = 十二时辰.项目
    .flatMap((项目) => 项目.时段)
    .find((时段) => 时段.当前)?.风水禁忌;
  const 时辰规则 = 当前时段规则 ?? 判断全部时辰规则(
    配置结果,
    最终.日支,
    最终.时支,
    历法结果.农历.月,
  );

  return { 时间依据, 真太阳时结果, 最终, 历法结果, 四柱, 时辰规则, 十二时辰, 时辰配置错误: 已解析配置.错误 };
}
