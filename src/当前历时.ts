import type { 配置解析结果 } from "./规则/配置读取";
import { 判断全部时辰规则 } from "./规则/时辰规则";
import { 格式化四柱, 计算最终时间, 计算历法, 计算真太阳时 } from "./历法";
import type { 北京时间 } from "./历法/时间";

export type 时间依据 = "北京时间" | "真太阳时";

export function 计算当前历时(
  北京时间: 北京时间,
  请求时间依据: 时间依据,
  经度: number | null,
  配置结果: 配置解析结果[],
) {
  const 时间依据: 时间依据 = 请求时间依据 === "真太阳时" && 经度 !== null ? "真太阳时" : "北京时间";
  const 真太阳时结果 = 经度 === null ? null : 计算真太阳时(北京时间, 经度);
  const 最终 = 计算最终时间(北京时间, 时间依据 === "真太阳时" ? 经度 : null);
  const 历法结果 = 计算历法(最终.最终时间);
  const 四柱 = 格式化四柱({
    年柱: 历法结果.年柱,
    月柱: 历法结果.月柱,
    日柱: 历法结果.日柱,
    时柱: 最终.时柱,
  });
  const 时辰规则 = 判断全部时辰规则(
    配置结果,
    最终.日支,
    最终.时支,
    历法结果.农历.月,
  );

  return { 时间依据, 真太阳时结果, 最终, 历法结果, 四柱, 时辰规则 };
}
