import type { 择日候选 } from "./择日";

export type 展示等级 = "优先推荐" | "推荐" | "可以考虑" | "谨慎选择";

/** 只解释已裁断、已排序的主推荐；不参与择日计算或排序。 */
export function 映射择日展示等级(候选: 择日候选[]): 展示等级[] {
  let 稳妥序号 = 0;
  return 候选.map((日期) => {
    if (日期.推荐程度 === "谨慎选择") return "谨慎选择";
    const 序号 = 稳妥序号++;
    return 序号 === 0 ? "优先推荐" : 序号 === 1 ? "推荐" : "可以考虑";
  });
}
