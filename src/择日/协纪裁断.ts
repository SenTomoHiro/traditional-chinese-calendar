/**
 * 按卷十表的全部非空条件分支匹配。空白格本身也是已编译的“无匹配”结果。
 */
export function 匹配宜忌等第({ 月建, 命中, 有德 }: 等第输入): { 等第: 等第; 状态: 铺注状态; 依据: string } | null {
  const 严重序: Record<等第, number> = { 上: 0, 上次: 1, 中: 2, 次: 3, 下: 4, 下下: 5 };
  const 匹配 = 宜忌等第条件分支
    .filter((项) => 月属(月建, 项.月) && 全有(命中, ...项.条件))
    .sort((甲, 乙) => 严重序[乙.等第] - 严重序[甲.等第])[0];
  if (!匹配) return null;
  const 等第值 = 匹配.等第;
  const 状态: 铺注状态 = 等第值 === "上" ? "注宜"
    : 等第值 === "上次" ? (有德 ? "注宜" : "宜忌并注")
      : 等第值 === "中" || 等第值 === "次" ? (有德 ? "宜忌并注" : "注忌")
        : 等第值 === "下" ? (有德 ? "注忌" : "诸事皆忌") : "诸事皆忌";
  return { 等第: 等第值, 状态, 依据: `XJF10-YJDJ ${等第值}等：${月建}月${匹配.条件.join("、")}` };
}
