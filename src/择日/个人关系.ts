import type { 生辰八字结果 } from "../生辰八字";
import { 八字关系表, 地支藏干, 天干属性, 计算十神 } from "../八字分析";

export type 关系层级 = "严重不利" | "需要注意" | "有利关系" | "辅助关系";
export type 来源类型 = "古籍直接" | "古籍类推" | "其他古籍补充" | "GitHub案例参考";

export interface 个人关系项 {
  层级: 关系层级;
  说明: string;
  来源类型: 来源类型;
  依据: string;
}

export interface 个人日期关系 {
  标签: string;
  候选日柱: string;
  项目: 个人关系项[];
  最严重层级: 关系层级 | "无明显关系";
}

const 层级顺序: 关系层级[] = ["严重不利", "需要注意", "有利关系", "辅助关系"];

function 配对存在(甲: string, 乙: string, 表: readonly string[]): boolean {
  return 甲 !== 乙 && 表.some((对) => (对[0] === 甲 && 对[1] === 乙) || (对[0] === 乙 && 对[1] === 甲));
}

function 干关系(日干: string, 命干: string): string {
  const 日 = 天干属性[日干 as keyof typeof 天干属性];
  const 命 = 天干属性[命干 as keyof typeof 天干属性];
  if (!日 || !命) return "";
  const 生序 = ["木", "火", "土", "金", "水"];
  const 生日 = 生序[(生序.indexOf(日.五行) + 1) % 5];
  const 生命 = 生序[(生序.indexOf(命.五行) + 1) % 5];
  const 克: Record<string, string> = { 木: "土", 火: "金", 土: "水", 金: "木", 水: "火" };
  if (日.五行 === 命.五行) return "同类";
  if (生日 === 命.五行) return "候选日干生事主日干";
  if (生命 === 日.五行) return "事主日干生候选日干";
  if (克[日.五行] === 命.五行) return "候选日干克事主日干";
  if (克[命.五行] === 日.五行) return "事主日干克候选日干";
  return "";
}

function 支关系(候选支: string, 命支: string, 对象: string): 个人关系项[] {
  const 结果: 个人关系项[] = [];
  const { 六合组, 六冲组, 六害组, 六破组, 三合组 } = 八字关系表;
  if (配对存在(候选支, 命支, 六合组)) 结果.push({ 层级: "有利关系", 说明: `候选日支${候选支}与${对象}${命支}六合`, 来源类型: "古籍类推", 依据: "《协纪辨方书》造葬、修方域中的命主生合关系，跨事项仅用于适配与排序" });
  if (配对存在(候选支, 命支, 六冲组)) 结果.push({ 层级: 对象.includes("日支") ? "严重不利" : "需要注意", 说明: `候选日支${候选支}与${对象}${命支}相冲`, 来源类型: "古籍类推", 依据: "古籍造葬本命冲克关系推广；非卷十一通用绝对禁日" });
  if (配对存在(候选支, 命支, 六害组)) 结果.push({ 层级: "需要注意", 说明: `候选日支${候选支}与${对象}${命支}相害`, 来源类型: "古籍类推", 依据: "地支六害作为个性适配证据，不单独作硬禁" });
  if (配对存在(候选支, 命支, 六破组)) 结果.push({ 层级: "需要注意", 说明: `候选日支${候选支}与${对象}${命支}相破`, 来源类型: "古籍类推", 依据: "地支相破作为个性适配证据，不单独作硬禁" });
  const 三刑对 = ["寅巳", "巳申", "申寅", "丑戌", "戌未", "未丑", "子卯", "卯子"];
  if (候选支 !== 命支 && (三刑对.includes(`${候选支}${命支}`) || 三刑对.includes(`${命支}${候选支}`))) 结果.push({ 层级: "需要注意", 说明: `候选日支${候选支}与${对象}${命支}见刑`, 来源类型: "古籍类推", 依据: "地支刑关系用于个性适配提醒，不单独作跨事项硬禁" });
  if (候选支 === 命支 && ["辰", "午", "酉", "亥"].includes(命支)) 结果.push({ 层级: "需要注意", 说明: `候选日支与${对象}${命支}同支，见自刑关系`, 来源类型: "其他古籍补充", 依据: "地支自刑只作关系提醒" });
  const 同组 = 三合组.find((组) => 组.支.includes(候选支 as never) && 组.支.includes(命支 as never));
  if (同组 && 候选支 !== 命支) 结果.push({ 层级: "有利关系", 说明: `候选日支${候选支}与${对象}${命支}同属${同组.支.join("、")}三合${同组.局}`, 来源类型: "古籍类推", 依据: "古籍三合关系用于适配排序，不声称单日两支已经成局" });
  return 结果;
}

export function 分析个人日期关系(标签: string, 命盘: 生辰八字结果, 候选日柱: string): 个人日期关系 {
  const 候选干 = 候选日柱[0]; const 候选支 = 候选日柱[1];
  const 命日干 = 命盘.日柱[0];
  const 项目: 个人关系项[] = [
    ...支关系(候选支, 命盘.年柱[1], "年支"),
    ...支关系(候选支, 命盘.日柱[1], "日支（夫妻宫）"),
  ];
  const 十神 = 计算十神(命日干, 候选干);
  项目.push({ 层级: ["正印", "偏印", "比肩", "食神"].includes(十神) ? "辅助关系" : "需要注意", 说明: `候选日干${候选干}对事主${命日干}日主为${十神}`, 来源类型: "古籍类推", 依据: "十神关系用于解释，不以单一十神直接定吉凶" });
  const 干合 = 配对存在(候选干, 命日干, 八字关系表.天干五合);
  if (干合) 项目.push({ 层级: "有利关系", 说明: `候选日干${候选干}与事主日干${命日干}相合`, 来源类型: "古籍类推", 依据: "天干五合作为适配证据；合化须结合命局辨析" });
  const 生克 = 干关系(候选干, 命日干);
  if (生克) 项目.push({ 层级: 生克.includes("克事主") ? "需要注意" : "辅助关系", 说明: 生克, 来源类型: "古籍类推", 依据: "天干生克用于排序解释，不作为跨事项绝对禁日" });
  const 年干生克 = 干关系(候选干, 命盘.年柱[0]).replaceAll("事主日干", "事主年干");
  if (年干生克) 项目.push({ 层级: 年干生克.includes("克事主") ? "需要注意" : "辅助关系", 说明: 年干生克, 来源类型: "古籍类推", 依据: "候选日干与年干关系用于个性适配，不作为跨事项绝对禁日" });
  if (配对存在(候选干, 命盘.年柱[0], 八字关系表.天干五合)) 项目.push({ 层级: "有利关系", 说明: `候选日干${候选干}与事主年干${命盘.年柱[0]}相合`, 来源类型: "古籍类推", 依据: "天干五合作为年命适配证据；合化须结合命局辨析" });
  const 日主禄位 = 八字关系表.禄位[命日干 as keyof typeof 八字关系表.禄位];
  if (候选支 === 日主禄位) 项目.push({ 层级: "有利关系", 说明: `候选日支${候选支}为事主${命日干}日主禄位`, 来源类型: "古籍类推", 依据: "古籍禄关系跨事项仅用于适配排序" });
  const 驿马组 = [
    { 命支: "申子辰", 马: "寅" }, { 命支: "寅午戌", 马: "申" },
    { 命支: "巳酉丑", 马: "亥" }, { 命支: "亥卯未", 马: "巳" },
  ];
  for (const [名称, 命支] of [["年支", 命盘.年柱[1]], ["日支", 命盘.日柱[1]]] as const) {
    if (驿马组.some((组) => 组.命支.includes(命支) && 组.马 === 候选支)) 项目.push({ 层级: "辅助关系", 说明: `候选日支${候选支}为事主${名称}${命支}所取驿马`, 来源类型: "古籍类推", 依据: "驿马只在适合流动的语境辅助解释，不一律定吉" });
  }
  const 天乙: Record<string, string> = { 甲: "丑未", 己: "丑未", 乙: "子申", 庚: "子申", 丙: "亥酉", 丁: "亥酉", 壬: "卯巳", 癸: "卯巳", 戊: "丑未", 辛: "丑未" };
  if (天乙[命日干]?.includes(候选支)) 项目.push({ 层级: "辅助关系", 说明: `候选日支${候选支}为事主${命日干}日主天乙贵人位`, 来源类型: "其他古籍补充", 依据: "天乙贵人作为辅助关系，不覆盖公共日课明确事项忌" });
  const 候选藏干 = 地支藏干[候选支 as keyof typeof 地支藏干];
  if (候选藏干) 项目.push({ 层级: "辅助关系", 说明: `候选日支${候选支}藏${候选藏干.map((干) => `${干}·${计算十神(命日干, 干)}`).join("、")}`, 来源类型: "古籍类推", 依据: "藏干仅作解释证据，不逐个累计排序权重" });
  const 命支们 = [命盘.年柱[1], 命盘.月柱[1], 命盘.日柱[1], 命盘.时柱[1]];
  const 明显 = 八字关系表.三合组.find((组) => 组.支.includes(候选支 as never) && 组.支.filter((支) => 命支们.includes(支)).length >= 2);
  if (明显) 项目.push({ 层级: "有利关系", 说明: `候选日支${候选支}与命局已有地支共同形成${明显.支.join("、")}三合${明显.局}线索`, 来源类型: "古籍类推", 依据: "完整三合关系仅作结构证据，是否成化仍需审全局" });
  const 最严重层级 = 层级顺序.find((层级) => 项目.some((项) => 项.层级 === 层级)) ?? "无明显关系";
  return { 标签, 候选日柱, 项目, 最严重层级 };
}

export function 双方共同结论(甲: 个人日期关系, 乙: 个人日期关系): string {
  if (甲.项目.some((项) => 项.层级 === "严重不利") || 乙.项目.some((项) => 项.层级 === "严重不利")) {
    const 不利方 = [甲, 乙].filter((方) => 方.项目.some((项) => 项.层级 === "严重不利")).map((方) => 方.标签).join("、");
    return `对${不利方}存在重要不利关系，双方排序靠后；这是跨事项类推，不冒充公共日课硬禁`;
  }
  if ([甲, 乙].every((方) => 方.项目.some((项) => 项.层级 === "有利关系"))) return "双方均有有利关系，可列共同优先候选";
  if ([甲, 乙].some((方) => 方.项目.some((项) => 项.层级 === "需要注意"))) return "至少一方有需要注意的关系，宜与公共日课及择时合看";
  return "双方未见严重冲突，保持对称比较";
}
