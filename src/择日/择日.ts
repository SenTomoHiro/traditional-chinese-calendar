function 公共事项结论(事项: (typeof 事项映射)[现代事项][number], 月建: string, 日柱: string, 原命中: string[], 日期事实: 已核日期事实): 古籍事项结论 {
  const 命中 = new Set([...原命中, ...命中四德(月建, 日柱[0]), ...展开事实名称(日期事实.协纪事实)]);
  const 规则 = 获取规则(事项.配置名);
  const 宜证据 = [...new Set(规则.flatMap((项) => 项.宜.filter((条件) => 命中.has(条件))))];
  let 忌证据 = [...new Set(规则.flatMap((项) => 项.忌.filter((条件) => 命中.has(条件))))];
  // 同位异名只保留一个事实证据，避免月破/大耗等在展示与排序中被重复理解。
  if (忌证据.includes("月破")) 忌证据 = 忌证据.filter((项) => 项 !== "大耗");
  const 待校: string[] = [];
  let 强制诸事忌 = false;
  const 有德 = 命中.has("天德") || 命中.has("月德") || 命中.has("天德合") || 命中.has("月德合");
  const 等第 = 匹配宜忌等第({ 月建, 命中, 有德 });
  const 明确相抵 = 有德 && "辰戌丑未".includes(月建) && ["闭日", "官日", "天吏"].every((名) => 命中.has(名));

  const 婚姻遇德犹忌 = ["结婚姻", "纳采问名", "嫁娶"].includes(事项.id) && 命中.has("八专");
  const 嫁娶专忌 = 事项.id === "嫁娶" && ["亥日", "厌对", "四忌", "四穷"].some((名) => 命中.has(名));
  const 专忌 = 婚姻遇德犹忌 || 嫁娶专忌 || (事项.id === "安床" && 命中.has("申日")) || (事项.id === "出行" && 命中.has("巳日"));
  const 九项ID = new Set(["结婚姻", "纳采问名", "嫁娶", "移徙", "安床", "开市", "立券交易", "出行", "祈福"]);
  if (九项ID.has(事项.id) && (命中.has("四离") || 命中.has("四绝"))) 忌证据.push(...["四离", "四绝"].filter((名) => 命中.has(名)));
  if (事项.id === "祈福" && 命中.has("上朔")) 忌证据.push("上朔");
  if (["开市", "立券交易"].includes(事项.id)) 忌证据.push(...["长星", "短星"].filter((名) => 命中.has(名)));
  if (["开市", "立券交易"].includes(事项.id) && 日期事实.长短星闰月未定) {
    待校.push("长星/短星原表未说明闰月沿用方式");
  }
  const 晦日 = 命中.has("晦日");
  const 不注日 = 命中.has("月忌日") || (事项.id === "祈福" && 命中.has("无禄")) || (["结婚姻", "纳采问名", "嫁娶", "移徙", "开市", "立券交易", "出行"].includes(事项.id) && 命中.has("二至二分"));

  if (等第?.等第 === "上" && 命中.has("收日") && 命中.has("劫煞") && 命中.has("六合")) {
    忌证据 = 忌证据.filter((项) => !["收日", "劫煞"].includes(项));
  }
  if (等第?.等第 === "上次" && 命中.has("开日") && 命中.has("灾煞") && 有德) {
    忌证据 = 忌证据.filter((项) => 项 !== "灾煞");
  }
  if (等第?.状态 === "诸事皆忌") 强制诸事忌 = true;
  待校.push(...日期事实.待校);
  const 去重忌 = [...new Set(忌证据)]; 忌证据 = 去重忌;
  let 状态: 裁断状态; let 铺注状态: 铺注状态; let 结论: string;
  if (待校.length > 0) {
    状态 = "资料未全"; 铺注状态 = "资料未全"; 结论 = "实际遇到闰月长星/短星候选日数，原书未说明闰月沿用方式，故本事项不作终判";
  }
  else if (强制诸事忌) { 状态 = "已裁断"; 铺注状态 = "诸事皆忌"; 结论 = `命中卷十已核的诸事皆忌分支${等第 ? `（${等第.依据}）` : ""}，本事项不优先`; }
  else if (专忌) { 状态 = "已裁断"; 铺注状态 = "注忌"; 结论 = "命中卷十百忌/事项专忌，普通德合与宜神不覆盖此忌"; }
  else if (不注日) { 状态 = "已裁断"; 铺注状态 = "宜忌皆不注"; 结论 = "命中卷十限定的不注事项，本事项宜忌皆不注；不等同吉日"; }
  else if (晦日) { 状态 = "已裁断"; 铺注状态 = 忌证据.length > 0 ? "注忌" : "宜忌皆不注"; 结论 = 忌证据.length > 0 ? "晦日本身不注宜，另有独立忌证据，故注忌" : "晦日余事虽不忌亦不注宜，本事项宜忌皆不注"; }
  else if (明确相抵 && 忌证据.length > 0) { 状态 = "已裁断"; 铺注状态 = "宜忌皆不注"; 结论 = "辰戌丑未月闭日并官日、天吏，与德并则吉凶相抵，卷十明定不宜不忌；关联事项按铺注条例有限联动"; }
  else if (宜证据.length > 0 && 忌证据.length > 0 && 等第) {
    状态 = "已裁断"; 铺注状态 = 等第.状态; 结论 = `${等第.依据}；按${有德 ? "有德" : "无德"}分支为${铺注状态}`;
  }
  else if (宜证据.length > 0 && 忌证据.length > 0) {
    状态 = "已裁断"; 铺注状态 = "宜忌并注"; 结论 = "原始宜、忌证据同时出现，且未命中卷十更改注法的特定等第分支，故据原表并注；不作数量抵消";
  }
  else if (宜证据.length > 0 || 忌证据.length > 0) {
    状态 = "已裁断"; 铺注状态 = 宜证据.length > 0 ? "注宜" : "注忌"; 结论 = 宜证据.length > 0 ? "在当前已核规则内注宜，仍须与个人关系和时辰合看" : "在当前已核规则内注忌，不列优先";
  } else { 状态 = "无明确注宜忌"; 铺注状态 = "宜忌皆不注"; 结论 = "当前已核规则未明确注宜或注忌，不等于吉日"; }
  if (["入宅", "归火"].includes(事项.id)) 结论 += "；此处裁断迁居日课，宅向、中宫、安香归火等空间条件保持独立，不与移徙或安床混同";
  return { id: 事项.id, 名称: 事项.名称, 状态, 铺注状态, 宜证据, 忌证据, 结论, 来源: 事项.来源, 待校: [...new Set(待校)] };
}

function 时支关系(时支: string, 人物: 生辰八字结果): { 有利: string[]; 注意: string[] } {
  const 有利: string[] = []; const 注意: string[] = [];
  for (const [名称, 命支] of [["年支", 人物.年柱[1]], ["日支", 人物.日柱[1]]] as const) {
    if (时支 !== 命支 && 八字关系表.六合组.some((对) => (对[0] === 时支 && 对[1] === 命支) || (对[0] === 命支 && 对[1] === 时支))) 有利.push(`时支${时支}与事主${名称}${命支}六合`);
    if (时支 !== 命支 && 八字关系表.六冲组.some((对) => (对[0] === 时支 && 对[1] === 命支) || (对[0] === 命支 && 对[1] === 时支))) 注意.push(`时支${时支}冲事主${名称}${命支}`);
  }
  return { 有利, 注意 };
}

function 选择时辰(日期: 北京时间, 事项: 现代事项, 人物: 生辰八字结果[], 时间依据: 时间依据, 经度: number | null, 配置: 配置解析结果[]): 推荐时辰[] {
  const 已解析 = 初始化时辰配置(配置);
  const 概览 = 创建十二时辰概览(日期, 时间依据, 经度, 已解析.时辰吉凶, 已解析.详细时辰, 配置);
  const 古籍名 = 事项映射[事项].flatMap((项) => 项.配置名);
  return 概览.项目.flatMap((项) => 项.时段).map((时段): 推荐时辰 => {
    const 有利 = [`${时段.值神} · ${时段.吉凶}`]; const 注意: string[] = []; const 待校: string[] = [];
    const 时宜 = 时段.详情.时宜.filter((名称) => 古籍名.includes(名称));
    const 时忌 = 时段.详情.时忌.filter((名称) => 古籍名.includes(名称));
    if (时宜.length > 0) 有利.push(`时宜：${时宜.join("、")}`);
    if (时忌.length > 0) 注意.push(`时忌：${时忌.join("、")}`);
    人物.forEach((命盘, 索引) => {
      const 关系 = 时支关系(时段.时支, 命盘);
      有利.push(...关系.有利.map((项) => `${人物.length > 1 ? `${索引 === 0 ? "甲方" : "乙方"}：` : ""}${项}`));
      注意.push(...关系.注意.map((项) => `${人物.length > 1 ? `${索引 === 0 ? "甲方" : "乙方"}：` : ""}${项}`));
      有利.push(`时干${时段.时柱[0]}对事主日主为${计算十神(命盘.日柱[0], 时段.时柱[0])}`);
    });
    if (时段.详情.凶煞.includes("旬空")) 注意.push("旬空：卷三十四明定出行须审此时忌");
    if (时段.详情.凶煞.includes("路空")) {
      注意.push("路空（截路空亡）：卷七起例命中，卷三十四明定出行须审此时忌");
    }
    const 等级 = 注意.length > 0 ? "谨慎" : 时段.吉凶 === "吉" && (时宜.length > 0 || 有利.length > 1) ? "优先" : "可考虑";
    return { 名称: 时段.名称, 时间范围: 时段.时间范围, 时柱: 时段.时柱, 等级, 有利, 注意, 待校 };
  }).sort((甲, 乙) => ({ 优先: 0, 可考虑: 1, 谨慎: 2 })[甲.等级] - ({ 优先: 0, 可考虑: 1, 谨慎: 2 })[乙.等级]).slice(0, 3);
}

function 比较排序(甲: 择日候选, 乙: 择日候选): number {
  for (let i = 0; i < 甲.排序键.length; i += 1) if (甲.排序键[i] !== 乙.排序键[i]) return 甲.排序键[i] - 乙.排序键[i];
  return 甲.日期.localeCompare(乙.日期);
}

/**
 * 展示层筛选只消费已经排好序的候选，不参与古籍裁断和排序键计算。
 * 明确“不优先”的日期不进入主推荐；“资料未全”等谨慎候选仍可按原排序靠后展示。
 */
export function 选择主推荐(已排序候选: 择日候选[]): 择日候选[] {
  return 已排序候选
    .filter((候选) => 候选.推荐程度 !== "不优先")
    .slice(0, 5);
}

export function 执行择日(
  事项: 现代事项,
  开始日期: string,
  结束日期: string,
  人物输入: 择日人物输入[],
  时间依据: 时间依据,
  经度: number | null,
  配置: 配置解析结果[],
): 择日结果 {
  let 当前 = 解析日期(开始日期); const 结束 = 解析日期(结束日期);
  if (!当前 || !结束 || 格式日期(当前) > 格式日期(结束)) throw new Error("请输入有效的择日日期范围");
  const 人物 = 人物输入.map((输入) => {
    const 时间匹配 = /^([01]\d|2[0-3]):([0-5]\d)$/u.exec(输入.时间);
    const 日期 = 解析日期(输入.日期, 时间匹配 ? Number(时间匹配[1]) : 12);
    const 分 = 时间匹配 ? Number(时间匹配[2]) : -1;
    if (!日期 || 分 < 0) throw new Error(`${输入.标签}出生信息不完整`);
    return 计算生辰八字({ ...日期, 分 }, 输入.时间依据, 输入.经度);
  });
  const 候选: 择日候选[] = [];
  let 天数 = 0;
  while (当前 && 格式日期(当前) <= 格式日期(结束)) {
    if (天数 >= 93) throw new Error("首版单次最多查询93天，请缩短日期范围");
    const 最终 = 计算最终时间(当前, 时间依据 === "真太阳时" ? 经度 : null);
    const 历法 = 计算历法(最终.最终时间);
    const 日期事实 = 计算已核日期事实(最终.最终时间);
    const 公共日课 = 事项映射[事项].map((古籍事项) => 公共事项结论(古籍事项, 历法.月建, 历法.日柱, 历法.每日宜忌.命中条件, 日期事实));
    const 人物关系 = 人物.map((命盘, 索引) => 分析个人日期关系(人物输入[索引].标签, 命盘, 历法.日柱));
    const 共同结论 = 人物关系.length === 2 ? 双方共同结论(人物关系[0], 人物关系[1]) : null;
    const 推荐时辰 = 选择时辰(当前, 事项, 人物, 时间依据, 经度, 配置);
    const 公共严重 = Math.max(...公共日课.map((项) => ({ 注宜: 0, 宜忌皆不注: 0, 资料未全: 1, 宜忌并注: 2, 注忌: 3, 诸事皆忌: 4 })[项.铺注状态]));
    const 状态序 = Math.max(...公共日课.map((项) => ({ 已裁断: 0, 无明确注宜忌: 1, 资料未全: 3 })[项.状态]));
    const 资料缺口 = 公共日课.reduce((总数, 项) => 总数 + 项.待校.length, 0);
    const 严重人数 = 人物关系.filter((关系) => 关系.项目.some((项) => 项.层级 === "严重不利")).length;
    const 注意人数 = 人物关系.filter((关系) => 关系.项目.some((项) => 项.层级 === "需要注意")).length;
    const 有利人数 = 人物关系.filter((关系) => 关系.项目.some((项) => 项.层级 === "有利关系")).length;
    const 辅助人数 = 人物关系.filter((关系) => 关系.项目.some((项) => 项.层级 === "辅助关系")).length;
    const 优先时辰 = 推荐时辰.filter((时辰) => 时辰.等级 === "优先").length;
    const 推荐程度: 择日候选["推荐程度"] = 公共严重 >= 3 ? "不优先" : 公共严重 > 0 || 状态序 >= 2 || 严重人数 ? "谨慎选择" : 人物.length === 2 && 有利人数 === 2 ? "共同优先" : "可以考虑";
    const 有利原因 = [
      ...公共日课.flatMap((项) => 项.宜证据.map((证据) => `${项.名称}宜：${证据}`)),
      ...人物关系.flatMap((关系) => 关系.项目.filter((项) => 项.层级 === "有利关系").map((项) => `${关系.标签}：${项.说明}`)),
    ];
    const 需要注意 = [
      ...公共日课.flatMap((项) => 项.忌证据.map((证据) => `${项.名称}忌：${证据}`)),
      ...人物关系.flatMap((关系) => 关系.项目.filter((项) => ["严重不利", "需要注意"].includes(项.层级)).map((项) => `${关系.标签}：${项.说明}`)),
    ];
    const 日课待校 = 公共日课.some((项) => 项.状态 === "资料未全" || 项.待校.length > 0);
    const 宜忌并见 = 公共日课.some((项) => 项.铺注状态 === "宜忌并注");
    const 时辰待校 = 推荐时辰.some((项) => 项.待校.length > 0);
    const 资料完整说明 = 日课待校
      ? "本日实际命中待校条件，不能给完整古籍终判"
      : 宜忌并见
        ? "本日依卷十一原始注法宜忌并注，未作数量抵消"
        : 时辰待校
          ? "日课已按当前覆盖范围裁断；推荐时辰中有待校时神"
          : "当前命中的必要规则已在首版覆盖范围内";
    候选.push({
      日期: 格式日期(当前), 干支: `${历法.年柱}年 ${历法.月柱}月 ${历法.日柱}日`, 节气月: `${历法.月建}月`, 值星: `${历法.值星}日`,
      黄黑道: `${历法.日吉凶.天神} · ${历法.日吉凶.类型} · ${历法.日吉凶.吉凶}`,
      已核事实: [日期事实.长星 ? "长星" : "", 日期事实.短星 ? "短星" : "", 日期事实.四离 ? "四离" : "", 日期事实.四绝 ? "四绝" : ""].filter(Boolean),
      推荐程度, 公共日课, 人物关系, 共同结论, 推荐时辰,
      有利原因, 需要注意, 资料完整说明,
      排序键: [公共严重, 状态序, 资料缺口, 严重人数, 注意人数, -有利人数, -辅助人数, -优先时辰],
    });
    当前 = 加一天(当前); 天数 += 1;
  }
  const 已排序候选 = 候选.sort(比较排序);
  return {
    事项, 日期范围: `${开始日期} 至 ${结束日期}`, 人物, 候选: 已排序候选,
    推荐候选: 选择主推荐(已排序候选),
    说明: ["先比较公共严重忌、正式铺注状态和资料完整度，再逐方比较重要不利、有利与辅助关系；双人不取数学平均。", "个人关系中的跨事项古籍类推只影响分层排序，不作为公共日课硬禁。", "推荐时辰不能推翻明确坏日；夜子、早子和真太阳时均沿用正式历法入口。"],
  };
}

