function 解析日期(文本: string, 时 = 12): 北京时间 | null {
  const 匹配 = /^(\d{4})-(\d{2})-(\d{2})$/u.exec(文本);
  if (!匹配) return null;
  const 年 = Number(匹配[1]); const 月 = Number(匹配[2]); const 日 = Number(匹配[3]);
  const 校验 = new Date(Date.UTC(年, 月 - 1, 日));
  if (校验.getUTCFullYear() !== 年 || 校验.getUTCMonth() + 1 !== 月 || 校验.getUTCDate() !== 日) return null;
  return 创建北京时间(年, 月, 日, 时, 0, 0);
}

function 格式日期(时间: 北京时间): string { return `${时间.年}-${String(时间.月).padStart(2, "0")}-${String(时间.日).padStart(2, "0")}`; }
function 加一天(时间: 北京时间): 北京时间 {
  const 日期 = new Date(Date.UTC(时间.年, 时间.月 - 1, 时间.日 + 1, 12));
  return 创建北京时间(日期.getUTCFullYear(), 日期.getUTCMonth() + 1, 日期.getUTCDate(), 12);
}

function 节气前一日(年: number, 名称: Parameters<typeof 获取指定节气>[1]): string {
  const 节气 = 获取指定节气(年, 名称);
  const 日期 = new Date(Date.UTC(节气.年, 节气.月 - 1, 节气.日 - 1));
  return `${日期.getUTCFullYear()}-${String(日期.getUTCMonth() + 1).padStart(2, "0")}-${String(日期.getUTCDate()).padStart(2, "0")}`;
}

export function 计算已核日期事实(时间: 北京时间): 已核日期事实 {
  const 历法 = 计算历法(时间);
  const 日期 = 格式日期(时间);
  const 待校: string[] = [];
  if (历法.农历.是否闰月) 待校.push("长星/短星原表未说明闰月沿用方式");
  const 可查星 = !历法.农历.是否闰月;
  const 四离 = (["春分", "夏至", "秋分", "冬至"] as const).some((名称) => 节气前一日(时间.年, 名称) === 日期);
  const 四绝 = (["立春", "立夏", "立秋", "立冬"] as const).some((名称) => 节气前一日(时间.年, 名称) === 日期);
  return {
    长星: 可查星 && 长星日[历法.农历.月].includes(历法.农历.日),
    短星: 可查星 && 短星日[历法.农历.月].includes(历法.农历.日),
    四离,
    四绝,
    待校,
  };
}

