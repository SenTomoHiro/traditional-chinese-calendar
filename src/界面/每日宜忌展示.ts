import type { 每日宜忌结果 } from "../历法/每日宜忌";

export interface 每日宜忌展示 {
  日宜: string[];
  日忌: string[];
}

/** 只压缩页面展示，完整计算数组仍保留在每日宜忌结果中。 */
export function 创建每日宜忌展示(结果: Pick<每日宜忌结果, "宜" | "忌" | "诸事不宜" | "诸事皆宜">): 每日宜忌展示 {
  return {
    日宜: 结果.诸事皆宜 ? ["诸事皆宜"] : [...结果.宜],
    日忌: 结果.诸事不宜 ? ["诸事不宜"] : [...结果.忌],
  };
}
