import { 是同一天 } from "../日历/公历";
import { 刷新实时查询时间, type 查询时间状态 } from "../实时历时";
import type { 北京时间 } from "../历法/时间";

function 转为日期(时间: 北京时间): Date {
  return new Date(时间.年, 时间.月 - 1, 时间.日);
}

export interface 主日期时钟刷新结果 {
  今天: Date;
  所选日期: Date;
  时间查询: 查询时间状态;
  需要渲染: boolean;
}

/** 实时模式只更新时分；只有原本跟随“今天”时，跨午夜才把选择日期推进到新一天。 */
export function 刷新主日期实时时钟(
  所选日期: Date,
  原今天: Date,
  时间查询: 查询时间状态,
  当前北京时间: 北京时间,
): 主日期时钟刷新结果 {
  const 今天 = 转为日期(当前北京时间);
  const 日期已经变化 = !是同一天(原今天, 今天);
  const 原本选择今天 = 是同一天(所选日期, 原今天);
  const 实时模式 = 时间查询.模式 === "实时";

  return {
    今天,
    所选日期: 实时模式 && 原本选择今天 ? 今天 : 所选日期,
    时间查询: 刷新实时查询时间(时间查询, 当前北京时间),
    需要渲染: 实时模式 || 日期已经变化,
  };
}
