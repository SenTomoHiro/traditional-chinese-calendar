function 是干(值: string): 值 is 干 { return 值 in 干属性; }
function 生(五行: 五行): 五行 { return 相生次序[(相生次序.indexOf(五行) + 1) % 5]; }

export function 计算十神(日干: string, 他干: string): 十神 {
  if (!是干(日干) || !是干(他干)) throw new Error("十神计算收到无效天干");
  const 主 = 干属性[日干];
  const 他 = 干属性[他干];
  const 同阴阳 = 主.阳 === 他.阳;
  if (主.五行 === 他.五行) return 同阴阳 ? "比肩" : "劫财";
  if (生(主.五行) === 他.五行) return 同阴阳 ? "食神" : "伤官";
  if (相克[主.五行] === 他.五行) return 同阴阳 ? "偏财" : "正财";
  if (相克[他.五行] === 主.五行) return 同阴阳 ? "七杀" : "正官";
  return 同阴阳 ? "偏印" : "正印";
}

function 配对存在(甲: string, 乙: string, 表: string[]): boolean {
  return 甲 !== 乙 && 表.some((对) => (对[0] === 甲 && 对[1] === 乙) || (对[0] === 乙 && 对[1] === 甲));
}

function 位置柱(命盘: 生辰八字结果) {
  return [
    { 位置: "年柱", 柱: 命盘.年柱 }, { 位置: "月柱", 柱: 命盘.月柱 },
    { 位置: "日柱", 柱: 命盘.日柱 }, { 位置: "时柱", 柱: 命盘.时柱 },
  ];
}

function 生成干关系(柱: ReturnType<typeof 位置柱>): string[] {
  const 结果: string[] = [];
  for (let i = 0; i < 柱.length; i += 1) for (let j = i + 1; j < 柱.length; j += 1) {
    const 甲 = 柱[i].柱[0] as 干; const 乙 = 柱[j].柱[0] as 干;
    if (配对存在(甲, 乙, 天干五合)) 结果.push(`${柱[i].位置}${甲}与${柱[j].位置}${乙}相合（仅列合，不自动判化）`);
    else if (相克[干属性[甲].五行] === 干属性[乙].五行 || 相克[干属性[乙].五行] === 干属性[甲].五行) 结果.push(`${柱[i].位置}${甲}与${柱[j].位置}${乙}有天干相克关系`);
    else if (生(干属性[甲].五行) === 干属性[乙].五行) 结果.push(`${柱[i].位置}${甲}生${柱[j].位置}${乙}`);
    else if (生(干属性[乙].五行) === 干属性[甲].五行) 结果.push(`${柱[j].位置}${乙}生${柱[i].位置}${甲}`);
  }
  return [...new Set(结果)];
}

function 生成支关系(柱: ReturnType<typeof 位置柱>): string[] {
  const 结果: string[] = [];
  const 支们 = 柱.map((项) => 项.柱[1] as 支);
  for (let i = 0; i < 柱.length; i += 1) for (let j = i + 1; j < 柱.length; j += 1) {
    const 甲 = 支们[i]; const 乙 = 支们[j]; const 前缀 = `${柱[i].位置}${甲}与${柱[j].位置}${乙}`;
    if (配对存在(甲, 乙, 六合组)) 结果.push(`${前缀}六合`);
    if (配对存在(甲, 乙, 六冲组)) 结果.push(`${前缀}相冲`);
    if (配对存在(甲, 乙, 六害组)) 结果.push(`${前缀}相害`);
    if (配对存在(甲, 乙, 六破组)) 结果.push(`${前缀}相破`);
    if (甲 === 乙 && ["辰", "午", "酉", "亥"].includes(甲)) 结果.push(`${前缀}自刑`);
    if (["寅巳", "巳申", "申寅", "丑戌", "戌未", "未丑", "子卯", "卯子"].includes(`${甲}${乙}`) || ["寅巳", "巳申", "申寅", "丑戌", "戌未", "未丑", "子卯", "卯子"].includes(`${乙}${甲}`)) 结果.push(`${前缀}见刑`);
  }
  for (const 组合 of 三合组) if (组合.支.every((支) => 支们.includes(支))) 结果.push(`命局具${组合.支.join("、")}三合${组合.局}（仅列关系，不自动判成化）`);
  return [...new Set(结果)];
}

function 格名(十神名: 十神): string | null {
  return (["正官", "七杀", "正财", "偏财", "正印", "偏印", "食神", "伤官"] as 十神[]).includes(十神名) ? `${十神名}格候选` : null;
}

function 格局不利与救应(名称: string, 全部十神: 十神[]): Pick<格局候选, "不利条件" | "人工复核"> {
  const 不利条件: string[] = [];
  const 人工复核: string[] = [];
  if (名称.includes("正官")) {
    if (全部十神.includes("伤官")) 不利条件.push("命局见伤官，存在伤官损官线索");
    if (全部十神.includes("七杀")) 不利条件.push("官杀并见，须辨混杂与去留");
    if (全部十神.some((神) => 神 === "正印" || 神 === "偏印")) 人工复核.push("同时见印，需审是否形成护官救应及位置先后");
  } else if (名称.includes("七杀")) {
    if (!全部十神.some((神) => ["食神", "正印", "偏印"].includes(神))) 不利条件.push("未见明确食制或印化线索");
    人工复核.push("须审制杀、化杀、合杀是否得当，不能见杀即定格");
  } else if (名称.includes("财")) {
    if (全部十神.some((神) => 神 === "比肩" || 神 === "劫财")) 不利条件.push("见比劫，须审分财条件");
    人工复核.push("须审日主能否任财及食伤生财是否有情");
  } else if (名称.includes("印")) {
    if (全部十神.some((神) => 神 === "正财" || 神 === "偏财")) 不利条件.push("财印并见，须审是否坏印及位置先后");
    if (名称.includes("偏印") && 全部十神.includes("食神")) 不利条件.push("偏印与食神并见，须审是否构成夺食");
  } else if (名称.includes("食神")) {
    if (全部十神.includes("偏印")) 不利条件.push("见偏印，存在枭夺食线索");
    人工复核.push("须审食神是否有气、能否生财或制杀");
  } else if (名称.includes("伤官")) {
    if (全部十神.includes("正官")) 不利条件.push("伤官与正官并见，须审是否伤官见官");
    if (全部十神.some((神) => 神 === "正印" || 神 === "偏印")) 人工复核.push("同时见印，需审伤官佩印及先后位置");
  }
  if (人工复核.length === 0) 人工复核.push("格局成败仍须结合强弱、位置、制化与救应人工复核");
  return { 不利条件, 人工复核 };
}

export function 分析八字(命盘: 生辰八字结果, 性别: 性别): 八字分析结果 {
  const 柱 = 位置柱(命盘);
  const 日干 = 命盘.日柱[0] as 干;
  const 月支 = 命盘.月柱[1] as 支;
  const 主五行 = 干属性[日干].五行;
  const 藏干: 藏干项[] = 柱.map(({ 位置, 柱: 当前柱 }) => ({
    位置,
    地支: 当前柱[1] as 支,
    藏干: 地支藏干[当前柱[1] as 支].map((藏, 索引) => ({ 干: 藏, 十神: 计算十神(日干, 藏), 层次: 索引 === 0 ? "本气" : 索引 === 1 ? "中气" : "余气" })),
  }));
  const 可见干 = 柱.filter((项) => 项.位置 !== "日柱").map((项) => ({ 位置: 项.位置, 干: 项.柱[0] as 干 }));
  const 月藏 = 地支藏干[月支];
  const 透干 = 月藏.flatMap((藏) => 可见干.filter((项) => 项.干 === 藏).map((项) => `${月令名称(月支)}藏${藏}（${计算十神(日干, 藏)}）透于${项.位置}`));
  const 通根 = 藏干.flatMap((项) => 项.藏干.filter((藏) => 干属性[藏.干].五行 === 主五行).map((藏) => `日主${日干}通根于${项.位置}${项.地支}中${藏.层次}${藏.干}`));
  const 月本气神 = 计算十神(日干, 月藏[0]);
  const 得令 = [(["比肩", "劫财", "正印", "偏印"] as 十神[]).includes(月本气神)
    ? `月令${月支}本气${月藏[0]}为${月本气神}，对日主有生扶，是得令一侧证据`
    : `月令${月支}本气${月藏[0]}为${月本气神}，日主不直接得令，仍须合看根与全局`];
  const 得地 = 通根.length > 0 ? 通根 : ["四支藏干未见日主同五行根，是否借印与气势须人工复核"];
  const 助干 = 可见干.filter((项) => ["比肩", "劫财", "正印", "偏印"].includes(计算十神(日干, 项.干)));
  const 得势 = 助干.length > 0 ? 助干.map((项) => `${项.位置}${项.干}为${计算十神(日干, 项.干)}，构成生扶证据`) : ["年、月、时透干未见直接印比生扶"];
  const 全部证据 = [
    ...可见干.map((项) => `${项.位置}${项.干}${计算十神(日干, 项.干)}`),
    ...藏干.flatMap((项) => 项.藏干.map((藏) => `${项.位置}${项.地支}藏${藏.干}${藏.十神}`)),
  ];
  const 分类 = (神们: 十神[]) => 全部证据.filter((项) => 神们.some((神) => 项.endsWith(神)));
  const 全部十神 = [...可见干.map((项) => 计算十神(日干, 项.干)), ...藏干.flatMap((项) => 项.藏干.map((藏) => 藏.十神))];
  const 格局候选: 格局候选[] = [];
  for (const [索引, 藏] of 月藏.entries()) {
    const 十神名 = 计算十神(日干, 藏); const 名称 = 格名(十神名);
    if (!名称) continue;
    const 已透 = 可见干.some((项) => 项.干 === 藏);
    const 判断 = 格局不利与救应(名称, 全部十神);
    格局候选.push({
      名称, 级别: 索引 === 0 || 已透 ? "主要候选" : "兼见候选",
      成立依据: [`月令${月支}${索引 === 0 ? "本气" : 索引 === 1 ? "中气" : "余气"}藏${藏}，对日主为${十神名}`, 已透 ? `${藏}已透于天干` : `${藏}未透，仅作藏气候选`],
      ...判断,
    });
  }
  if (禄位[日干] === 月支) 格局候选.unshift({ 名称: "建禄候选", 级别: "主要候选", 成立依据: [`${日干}日主禄位在${月支}，恰临月令`], 不利条件: [], 人工复核: ["建禄须另取财官食伤，不能把比肩月令直接当普通正格"] });
  if (阳刃位[日干] === 月支) 格局候选.unshift({ 名称: "月刃候选", 级别: "人工复核", 成立依据: [`阳干${日干}月令临刃位${月支}`], 不利条件: [], 人工复核: ["须审官杀制刃及是否过制；阴干月刃口径本版不自动判断"] });
  const 季节 = (["亥", "子", "丑"].includes(月支) ? "寒" : ["巳", "午", "未"].includes(月支) ? "热" : ["申", "酉", "戌"].includes(月支) ? "燥" : "升发") as "寒" | "热" | "燥" | "升发";
  const 调候 = [`${月支}月属${季节 === "寒" ? "冬令偏寒" : 季节 === "热" ? "夏令偏热" : 季节 === "燥" ? "秋令偏燥" : "春令升发"}，调候需按日干逐月原条另审`, "本栏只提示寒暖燥湿，不把《穷通宝鉴》的逐月用字直接称为喜用神"];
  const 生扶 = 分类(["比肩", "劫财", "正印", "偏印"]);
  const 克项 = 分类(["正官", "七杀"]); const 泄 = 分类(["食神", "伤官"]); const 耗 = 分类(["正财", "偏财"]);
  return {
    性别, 命盘, 日主: `${日干}${主五行}`, 月令: `${月支}月 · 本气${月藏[0]}（${月本气神}）`, 藏干, 透干,
    通根, 得令, 得地, 得势, 全局结构: { 生扶, 克: 克项, 泄, 耗 }, 天干关系: 生成干关系(柱), 地支关系: 生成支关系(柱), 格局候选,
    调候,
    三套取用说明: {
      格局用: `以月令所藏与透干审格，当前列出${格局候选.map((项) => 项.名称).join("、") || "待审候选"}，不作唯一终判。`,
      扶抑: `生扶、克、泄、耗证据已分列；不使用五行个数或固定权重推唯一喜用。`,
      调候: `按${月支}月的寒暖燥湿单列，不能替代格局与扶抑。`,
    },
    通俗总结: [
      `这是${日干}${主五行}日主，先看${月支}月的季节力量，再看${通根.length > 0 ? "命局中已有根气" : "根气是否足够"}。`,
      `目前可核的生扶证据${生扶.length > 0 ? `见于${生扶.slice(0, 3).join("、")}` : "不明显"}；克泄耗仍需与位置和制化合看。`,
      `格局只列候选，不自动判从格、化气格或唯一喜用神。`,
    ],
    来源说明: "《三命通会》卷五、《子平真诠》格局框架、《滴天髓》衰旺论及《穷通宝鉴》调候分栏；机器仅列可核事实与候选。",
  };
}

