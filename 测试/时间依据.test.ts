import { describe, expect, it } from "vitest";
import { 计算当前历时 } from "../src/当前历时";
import { 读取全部配置 } from "../src/规则/配置读取";
import { 创建北京时间 } from "../src/历法/时间";

const 配置结果 = 读取全部配置();
const 接近午夜 = 创建北京时间(2026, 8, 9, 1, 0);

describe("统一时间依据切换", () => {
  it("北京时间与真太阳时切换会统一重算四柱和风水禁忌", () => {
    const 北京结果 = 计算当前历时(接近午夜, "北京时间", 60, 配置结果);
    const 真太阳结果 = 计算当前历时(接近午夜, "真太阳时", 60, 配置结果);
    const 切回北京 = 计算当前历时(接近午夜, "北京时间", 60, 配置结果);

    expect(北京结果.时间依据).toBe("北京时间");
    expect(真太阳结果.时间依据).toBe("真太阳时");
    expect(真太阳结果.四柱).not.toBe(北京结果.四柱);
    expect(真太阳结果.日级风水禁忌.规则).not.toEqual(北京结果.日级风水禁忌.规则);
    expect(真太阳结果.时辰规则).not.toEqual(北京结果.时辰规则);
    expect(真太阳结果.十二时辰.项目[0].时段[0].时间范围).not.toBe(北京结果.十二时辰.项目[0].时段[0].时间范围);
    expect(切回北京.四柱).toBe(北京结果.四柱);
    expect(切回北京.时辰规则).toEqual(北京结果.时辰规则);
    expect(切回北京.十二时辰).toEqual(北京结果.十二时辰);
  });

  it("真太阳时可以跨公历日，两种模式都由各自最终日期判断午夜换日", () => {
    const 北京结果 = 计算当前历时(接近午夜, "北京时间", 60, 配置结果);
    const 真太阳结果 = 计算当前历时(接近午夜, "真太阳时", 60, 配置结果);

    expect(北京结果.最终.最终时间).toMatchObject({ 年: 2026, 月: 8, 日: 9 });
    expect(真太阳结果.最终.最终时间).toMatchObject({ 年: 2026, 月: 8, 日: 8 });
    expect(真太阳结果.最终.日柱).not.toBe(北京结果.最终.日柱);
    expect(真太阳结果.日级风水禁忌.规则).not.toEqual(北京结果.日级风水禁忌.规则);
  });

  it("北京时间23点进入子时，真太阳时若仍在23点前就保持亥时", () => {
    const 北京结果 = 计算当前历时(创建北京时间(2026, 8, 9, 23, 0), "北京时间", 116.4, 配置结果);
    const 真太阳结果 = 计算当前历时(创建北京时间(2026, 8, 9, 23, 0), "真太阳时", 116.4, 配置结果);

    expect(北京结果.最终).toMatchObject({ 日柱: "乙卯", 时支: "子", 时柱: "丙子" });
    expect(真太阳结果.最终.最终时间.时).toBe(22);
    expect(真太阳结果.最终.日柱).toBe("乙卯");
    expect(真太阳结果.四柱).not.toBe(北京结果.四柱);
    expect(真太阳结果.时辰规则).not.toEqual(北京结果.时辰规则);
  });

  it("北京时间23点前后保持日柱并刷新时柱与风水禁忌", () => {
    const 边界前 = 计算当前历时(创建北京时间(2026, 8, 9, 22, 59), "北京时间", null, 配置结果);
    const 边界后 = 计算当前历时(创建北京时间(2026, 8, 9, 23, 0), "北京时间", null, 配置结果);

    expect(边界前.最终).toMatchObject({ 日柱: "乙卯", 时柱: "丁亥" });
    expect(边界后.最终).toMatchObject({ 日柱: "乙卯", 时柱: "丙子" });
    expect(边界后.时辰规则).not.toEqual(边界前.时辰规则);
  });

  it("北京时间午夜前后同步刷新日柱、时柱和值神概览", () => {
    const 夜子 = 计算当前历时(创建北京时间(2026, 8, 9, 23, 59), "北京时间", null, 配置结果);
    const 早子 = 计算当前历时(创建北京时间(2026, 8, 10, 0, 0), "北京时间", null, 配置结果);
    expect(夜子.最终).toMatchObject({ 日柱: "乙卯", 时支: "子", 时柱: "丙子" });
    expect(早子.最终).toMatchObject({ 日柱: "丙辰", 时支: "子", 时柱: "戊子" });
    expect(夜子.十二时辰.项目[0].时段.map((段) => 段.值神)).toEqual(["司命", "天牢"]);
    expect(早子.十二时辰.项目[0].时段.map((段) => 段.值神)).toEqual(["司命", "天牢"]);
  });

  it("没有定位时请求真太阳时会安全保持北京时间", () => {
    const 结果 = 计算当前历时(接近午夜, "真太阳时", null, 配置结果);
    expect(结果.时间依据).toBe("北京时间");
    expect(结果.真太阳时结果).toBeNull();
    expect(结果.最终.最终时间).toEqual(接近午夜);
  });

  it("北京时间模式仍会保留真太阳时明细供辅助区显示", () => {
    const 结果 = 计算当前历时(接近午夜, "北京时间", 116.4, 配置结果);
    expect(结果.时间依据).toBe("北京时间");
    expect(结果.真太阳时结果?.真太阳时).toBeDefined();
    expect(结果.最终.最终时间).toEqual(接近午夜);
  });
});
