import { describe, expect, it } from "vitest";
import { 更新手动查看键, 清除手动查看时辰, 选出查看时辰 } from "../src/界面/时辰查看";

const 时段 = (当前键: string) => ["子", "丑", "寅"].map((键) => ({ 键, 当前: 键 === 当前键 }));

describe("十二时辰常驻详情状态", () => {
  it("没有手动选择时默认查看当前时辰", () => {
    expect(选出查看时辰(时段("丑"), null)?.键).toBe("丑");
  });

  it("手动选择其他时辰后保持查看", () => {
    expect(选出查看时辰(时段("丑"), "寅")?.键).toBe("寅");
  });

  it("再次点击手动选中时辰不会收起", () => {
    expect(更新手动查看键("寅", false)).toBe("寅");
  });

  it("点击当前时辰后恢复自动跟随", () => {
    expect(更新手动查看键("丑", true)).toBeNull();
  });

  it("未手动选择时跨时辰会自动更新", () => {
    expect(选出查看时辰(时段("丑"), null)?.键).toBe("丑");
    expect(选出查看时辰(时段("寅"), null)?.键).toBe("寅");
  });

  it("已手动选择时实时更新不会抢回", () => {
    expect(选出查看时辰(时段("丑"), "子")?.键).toBe("子");
    expect(选出查看时辰(时段("寅"), "子")?.键).toBe("子");
  });

  it("无效手动键会回退到当前时辰", () => {
    expect(选出查看时辰(时段("丑"), "不存在")?.键).toBe("丑");
  });

  it("标题按钮清除手动选择并恢复当前查询时辰", () => {
    const 全部时段 = 时段("丑");
    expect(选出查看时辰(全部时段, "寅")?.键).toBe("寅");
    expect(选出查看时辰(全部时段, 清除手动查看时辰())?.键).toBe("丑");
  });
});
