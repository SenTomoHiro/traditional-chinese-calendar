import { describe, expect, it } from "vitest";
import { 计算当前历时 } from "../src/当前历时";
import { 创建北京时间, 平移时间, 计算日柱 } from "../src/历法";
import type { 农历日期 } from "../src/历法/农历";
import { 计算北斗, 二十八章经来源, 真经注来源, 解析北斗配置 } from "../src/规则/北斗";
import { 读取全部配置 } from "../src/规则/配置读取";

const 配置结果 = 读取全部配置();
const 解析结果 = 解析北斗配置(配置结果);
const 配置 = 解析结果.配置;

function 农历(月: number, 日: number, 是否闰月 = false): 农历日期 {
  return { 年: 2026, 月, 日, 是否闰月, 月名: `${月}月`, 日名: `${日}日`, 显示: `${月}月${日}日` };
}

describe("北斗三类信息", () => {
  it("三份中文配置完整解析", () => {
    expect(解析结果.错误).toEqual([]);
    expect(配置).not.toBeNull();
    expect(Object.keys(配置?.二十八章经 ?? {})).toHaveLength(12);
    expect(Object.keys(配置?.真经注 ?? {})).toHaveLength(12);
    expect(Object.keys(配置?.本命星官 ?? {})).toHaveLength(12);
  });

  it("八月十一两书同载时直接列出两部完整书名", () => {
    const 结果 = 计算北斗(配置, 农历(8, 11), "乙卯");
    expect(结果.斗降日.命中).toBe(true);
    expect(new Set(结果.斗降日.依据.map((依据) => 依据.来源))).toEqual(new Set([二十八章经来源, 真经注来源]));
    expect(结果.斗降日.来源显示).toBe(`${二十八章经来源}、${真经注来源}`);
  });

  it("八月初三只由真经注固定表和每月规则命中", () => {
    const 结果 = 计算北斗(配置, 农历(8, 3), "乙卯");
    expect(结果.斗降日.依据).toEqual(expect.arrayContaining([
      { 来源: 真经注来源, 规则: "8月3日" },
      { 来源: 真经注来源, 规则: "每月3日" },
    ]));
    expect(结果.斗降日.依据.some((依据) => 依据.来源 === 二十八章经来源)).toBe(false);
    expect(结果.斗降日.来源显示).toBe(真经注来源);
  });

  it("二月初三保留两书不同命中规则", () => {
    const 结果 = 计算北斗(配置, 农历(2, 3), "乙卯");
    expect(结果.斗降日.依据).toEqual(expect.arrayContaining([
      { 来源: 二十八章经来源, 规则: "2月3日" },
      { 来源: 真经注来源, 规则: "每月3日" },
    ]));
  });

  it.each(["甲子", "庚申"])("%s日独立命中真经注干支规则", (日柱) => {
    const 结果 = 计算北斗(配置, 农历(6, 12), 日柱);
    expect(结果.斗降日.依据).toEqual([{ 来源: 真经注来源, 规则: `${日柱}日` }]);
  });

  it("闰月只执行真经注明确的从前月规则", () => {
    const 结果 = 计算北斗(配置, 农历(8, 11, true), "乙卯");
    expect(结果.斗降日.依据.some((依据) => 依据.来源 === 二十八章经来源)).toBe(false);
    expect(结果.斗降日.依据).toContainEqual({ 来源: 真经注来源, 规则: "闰月从前月·8月11日" });
  });

  it("十二地支完整映射七元本命星官", () => {
    const 预期 = { 子: "贪狼", 丑: "巨门", 寅: "禄存", 卯: "文曲", 辰: "廉贞", 巳: "武曲", 午: "破军", 未: "武曲", 申: "廉贞", 酉: "文曲", 戌: "禄存", 亥: "巨门" };
    for (const [支, 星] of Object.entries(预期)) {
      const 结果 = 计算北斗(配置, 农历(6, 12), `甲${支}`);
      expect(结果.本命星官).toContain(星);
    }
  });

  it("连续六十日完整覆盖六十甲子并在第六十一日复现", () => {
    const 起点 = 创建北京时间(2000, 1, 7);
    const 六十日 = Array.from({ length: 60 }, (_, 索引) => 计算日柱(平移时间(起点, 索引 * 86_400)).日柱);
    expect(new Set(六十日).size).toBe(60);
    expect(六十日[0]).toBe("甲子");
    expect(计算日柱(平移时间(起点, 60 * 86_400)).日柱).toBe("甲子");
    for (const 日柱 of 六十日) expect(计算北斗(配置, 农历(6, 12), 日柱).本命下日).toBe(`${日柱}生人`);
  });

  it("夜子早子和真太阳时跨日均复用最终权威日柱", () => {
    const 夜子 = 计算当前历时(创建北京时间(2026, 8, 9, 23, 30), "北京时间", null, 配置结果);
    const 早子 = 计算当前历时(创建北京时间(2026, 8, 10, 0, 30), "北京时间", null, 配置结果);
    const 真太阳 = 计算当前历时(创建北京时间(2026, 8, 9, 1), "真太阳时", 60, 配置结果);
    expect(夜子.北斗.本命下日).toBe(`${夜子.历法结果.日柱}生人`);
    expect(早子.北斗.本命下日).toBe(`${早子.历法结果.日柱}生人`);
    expect(早子.北斗.本命下日).not.toBe(夜子.北斗.本命下日);
    expect(真太阳.北斗.本命下日).toBe(`${真太阳.历法结果.日柱}生人`);
  });
});
