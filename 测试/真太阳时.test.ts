import { describe, expect, it } from "vitest";
import { 从时间戳读取北京时间, 创建北京时间 } from "../src/历法/时间";
import {
  计算均时差分钟,
  计算最终时间,
  计算时支,
  计算时柱,
  计算真太阳时,
  计算经度修正分钟,
} from "../src/历法/真太阳时";

const 时刻 = (年: number, 月: number, 日: number, 时 = 12, 分 = 0, 秒 = 0) =>
  创建北京时间(年, 月, 日, 时, 分, 秒);

describe("北京时间不依赖设备时区", () => {
  it("UTC 日期尚未换日时能正确进入北京时间次日", () => {
    expect(从时间戳读取北京时间(new Date("2026-08-08T16:05:06Z"))).toEqual({
      年: 2026,
      月: 8,
      日: 9,
      时: 0,
      分: 5,
      秒: 6,
    });
  });

  it("固定时间戳始终加八小时", () => {
    expect(从时间戳读取北京时间(new Date("2026-08-09T00:05:06Z"))).toMatchObject({
      年: 2026,
      月: 8,
      日: 9,
      时: 8,
      分: 5,
      秒: 6,
    });
  });
});

describe("十二时辰边界", () => {
  it.each([
    [23, 0, "子"],
    [0, 59, "子"],
    [1, 0, "丑"],
    [2, 59, "丑"],
    [3, 0, "寅"],
    [4, 59, "寅"],
    [5, 0, "卯"],
    [6, 59, "卯"],
    [7, 0, "辰"],
    [8, 59, "辰"],
    [9, 0, "巳"],
    [10, 59, "巳"],
    [11, 0, "午"],
    [12, 59, "午"],
    [13, 0, "未"],
    [14, 59, "未"],
    [15, 0, "申"],
    [16, 59, "申"],
    [17, 0, "酉"],
    [18, 59, "酉"],
    [19, 0, "戌"],
    [20, 59, "戌"],
    [21, 0, "亥"],
    [22, 59, "亥"],
  ] as const)("%i:%i 属于%s时", (时, 分, 预期) => {
    expect(计算时支(时刻(2026, 8, 9, 时, 分))).toBe(预期);
  });

  it("按秒严格在 01:00 切换子时和丑时", () => {
    expect(计算时支(时刻(2026, 8, 9, 0, 59, 59))).toBe("子");
    expect(计算时支(时刻(2026, 8, 9, 1, 0, 0))).toBe("丑");
  });
});

describe("五鼠遁时柱", () => {
  it.each([
    ["甲子", "甲子"],
    ["己巳", "甲子"],
    ["乙丑", "丙子"],
    ["庚午", "丙子"],
    ["丙寅", "戊子"],
    ["辛未", "戊子"],
    ["丁卯", "庚子"],
    ["壬申", "庚子"],
    ["戊辰", "壬子"],
    ["癸酉", "壬子"],
  ])("%s 日从 %s 起子时", (日柱, 预期) => {
    expect(计算时柱(日柱, "子")).toBe(预期);
  });

  it("时干随十二时支顺排", () => {
    expect(计算时柱("甲子", "丑")).toBe("乙丑");
    expect(计算时柱("甲子", "亥")).toBe("乙亥");
  });

  it("23:30 与次日 00:30 同属子时但因 0:00 换日而时柱不同", () => {
    const 当晚 = 计算最终时间(时刻(2026, 8, 9, 23, 30), null);
    const 次日 = 计算最终时间(时刻(2026, 8, 10, 0, 30), null);
    expect(当晚).toMatchObject({ 日柱: "乙卯", 时支: "子", 时柱: "丙子" });
    expect(次日).toMatchObject({ 日柱: "丙辰", 时支: "子", 时柱: "戊子" });
  });
});

describe("真太阳时修正", () => {
  it("东经 120° 的经度修正为零", () => {
    expect(计算经度修正分钟(120)).toBe(0);
  });

  it("经度每向东一度增加四分钟，向西反向修正", () => {
    expect(计算经度修正分钟(121)).toBe(4);
    expect(计算经度修正分钟(116)).toBe(-16);
  });

  it("拒绝无效经度", () => {
    expect(() => 计算经度修正分钟(181)).toThrow(RangeError);
    expect(() => 计算经度修正分钟(Number.NaN)).toThrow(RangeError);
  });

  it("均时差随日期变化并符合 NOAA 公式的分钟结果", () => {
    expect(计算均时差分钟(时刻(2026, 2, 11))).toBeCloseTo(-14.2, 1);
    expect(计算均时差分钟(时刻(2026, 11, 3))).toBeCloseTo(16.37, 1);
  });

  it("北京城区经度案例同时应用经度修正和均时差", () => {
    const 结果 = 计算真太阳时(时刻(2026, 8, 9, 12), 116.4);
    expect(结果.经度修正分钟).toBeCloseTo(-14.4, 6);
    expect(结果.均时差分钟).toBeCloseTo(-5.82, 1);
    expect(结果.真太阳时).toEqual(时刻(2026, 8, 9, 11, 39, 47));
  });

  it("大幅向西修正可跨到前一天并切换日柱", () => {
    const 结果 = 计算最终时间(时刻(2026, 8, 9, 1), 60);
    expect(结果.最终时间).toMatchObject({ 年: 2026, 月: 8, 日: 8 });
    expect(结果.日柱).not.toBe("乙卯");
  });

  it("大幅向东修正可跨到后一天并切换日柱", () => {
    const 结果 = 计算最终时间(时刻(2026, 8, 9, 23), 180);
    expect(结果.最终时间).toMatchObject({ 年: 2026, 月: 8, 日: 10 });
    expect(结果.日柱).toBe("丙辰");
  });

  it("没有经度时完整回退到北京时间", () => {
    const 输入 = 时刻(2026, 8, 9, 23, 30);
    expect(计算最终时间(输入, null)).toMatchObject({
      真太阳时: null,
      最终时间: 输入,
      计算依据: "北京时间（未取得定位）",
    });
  });
});
