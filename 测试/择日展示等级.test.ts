import { describe, expect, it } from "vitest";
import { 映射择日展示等级 } from "../src/择日/结果等级";
import type { 择日候选 } from "../src/择日/择日";

const 候选 = (等级: 择日候选["推荐程度"]) => ({ 推荐程度: 等级 }) as 择日候选;

describe("择日四档展示", () => {
  it("按既有排序对稳妥候选分层，谨慎候选始终保留注意含义", () => {
    expect(映射择日展示等级([
      候选("可以考虑"), 候选("谨慎选择"), 候选("共同优先"), 候选("可以考虑"), 候选("谨慎选择"),
    ])).toEqual(["优先推荐", "谨慎选择", "推荐", "可以考虑", "谨慎选择"]);
  });

  it("无稳妥候选时不会凭名次抬高谨慎日期", () => {
    expect(映射择日展示等级([候选("谨慎选择"), 候选("谨慎选择")])).toEqual(["谨慎选择", "谨慎选择"]);
  });
});
