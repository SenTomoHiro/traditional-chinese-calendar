import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { 获取指定节气 } from "../src/历法/节气";
import { 创建北京时间, 平移时间 } from "../src/历法/时间";
import {
  汇总当日风水状态,
  获取罗睺季节,
  计算日级风水禁忌,
  type 日级风水判断,
} from "../src/规则/日级风水禁忌";
import { 读取全部配置 } from "../src/规则/配置读取";
import { 判断全部时辰规则 } from "../src/规则/时辰规则";

const 配置 = 读取全部配置();
const 九类配置文件 = [
  "年罗睺日.txt",
  "季罗睺日.txt",
  "月罗睺日.txt",
  "阴阳宅禁日.txt",
  "逐年杀风水师日.txt",
  "逐月杀风水师日.txt",
  "杀师时.txt",
  "造葬杀风水师时.txt",
  "逐月杀风水师时.txt",
];
const 时刻 = (年: number, 月: number, 日: number, 时 = 12, 分 = 0) => 创建北京时间(年, 月, 日, 时, 分);
const 命中名称 = (年: number, 月: number, 日: number) => 计算日级风水禁忌(配置, 时刻(年, 月, 日)).命中.map((规则) => 规则.名称);

describe("九类风水禁忌完整性与日时分层", () => {
  it("九份配置全部存在且解析无误", () => {
    for (const 文件名 of 九类配置文件) {
      const 结果 = 配置.find((项目) => 项目.文件名 === 文件名);
      expect(结果, 文件名).toBeDefined();
      expect(结果?.错误, 文件名).toEqual([]);
      expect(结果?.规则.length, 文件名).toBeGreaterThan(0);
    }
  });

  it("六类日级规则都有固定命中案例", () => {
    expect(命中名称(2025, 2, 14)).toEqual(expect.arrayContaining(["年罗睺日", "逐年杀风水师日"]));
    expect(命中名称(2025, 2, 15)).toContain("季罗睺日");
    expect(命中名称(2025, 1, 5)).toContain("月罗睺日");
    expect(命中名称(2025, 1, 1)).toContain("阴阳宅禁日");
    expect(命中名称(2025, 1, 2)).toContain("逐月杀风水师日");
  });

  it("逐年杀风水师日命中时保留对应方位", () => {
    const 结果 = 计算日级风水禁忌(配置, 时刻(2025, 2, 14));
    expect(结果.命中.find((规则) => 规则.名称 === "逐年杀风水师日")).toMatchObject({
      说明: "甲寅日命中",
      方位: "甲干寅支方",
    });
  });

  it("季罗睺严格在立春交节时刻切换", () => {
    const 立春 = 获取指定节气(2026, "立春");
    expect(获取罗睺季节(平移时间(立春, -60))).toBe("冬季");
    expect(获取罗睺季节(立春)).toBe("春季");
  });

  it("戌年丁未年罗睺与辛未逐年杀师保持独立", () => {
    const 丁未 = 计算日级风水禁忌(配置, 时刻(2031, 1, 7));
    const 辛未 = 计算日级风水禁忌(配置, 时刻(2031, 1, 31));
    expect(丁未.命中.find((规则) => 规则.名称 === "年罗睺日")?.说明).toBe("丁未日命中");
    expect(丁未.命中.some((规则) => 规则.名称 === "逐年杀风水师日")).toBe(false);
    expect(辛未.命中.find((规则) => 规则.名称 === "逐年杀风水师日")).toMatchObject({
      说明: "辛未日命中",
      方位: "辛干未支方",
    });
    expect(辛未.命中.some((规则) => 规则.名称 === "年罗睺日")).toBe(false);
  });

  it("锁定己巳、戌与未日午辰时的正式写法", () => {
    const 年罗睺文本 = readFileSync(resolve(process.cwd(), "配置/年罗睺日.txt"), "utf8");
    const 逐年文本 = readFileSync(resolve(process.cwd(), "配置/逐年杀风水师日.txt"), "utf8");
    const 杀师时文本 = readFileSync(resolve(process.cwd(), "配置/杀师时.txt"), "utf8");
    expect(年罗睺文本).toContain("申年：己巳日");
    expect(逐年文本).toContain("戌年：辛未日；辛干未支方");
    expect(杀师时文本).toContain("未日：午时、辰时");
    expect(`${年罗睺文本}${逐年文本}${杀师时文本}`).not.toMatch(/已巳|戍/u);
  });

  it("三类时辰规则仍独立命中且十月明确无逐月时规则", () => {
    expect(判断全部时辰规则(配置, "子", "丑", 1).find((规则) => 规则.名称 === "杀师时")?.状态).toBe("命中");
    expect(判断全部时辰规则(配置, "子", "卯", 1).find((规则) => 规则.名称 === "造葬杀风水师时")?.状态).toBe("命中");
    expect(判断全部时辰规则(配置, "子", "卯", 1).find((规则) => 规则.名称 === "逐月杀风水师时")?.状态).toBe("命中");
    expect(判断全部时辰规则(配置, "子", "子", 10).find((规则) => 规则.名称 === "逐月杀风水师时")?.状态).toBe("无规则");
  });
});

describe("当日风水状态汇总", () => {
  const 规则 = (名称: 日级风水判断["名称"], 层级: 日级风水判断["层级"]): 日级风水判断 => ({
    名称,
    层级,
    状态: "命中",
    说明: "测试命中",
  });

  it("无日级禁忌时显示当日宜", () => {
    expect(计算日级风水禁忌(配置, 时刻(2025, 1, 3))).toMatchObject({ 命中: [], 犯忌层级: [], 当日状态: "当日宜" });
  });

  it.each([
    [[规则("季罗睺日", "季")], "日犯季忌"],
    [[规则("月罗睺日", "月")], "日犯月忌"],
    [[规则("阴阳宅禁日", "日")], "阴阳宅禁日"],
    [[规则("年罗睺日", "年"), 规则("月罗睺日", "月")], "日犯年/月忌"],
    [[规则("年罗睺日", "年"), 规则("季罗睺日", "季"), 规则("月罗睺日", "月")], "日犯年/季/月忌"],
    [[规则("季罗睺日", "季"), 规则("月罗睺日", "月"), 规则("阴阳宅禁日", "日")], "日犯季/月忌 · 阴阳宅禁日"],
  ] as const)("按年季月日顺序生成层级提示 %#", (输入, 期望) => {
    expect(汇总当日风水状态([...输入]).当日状态).toBe(期望);
  });

  it("同一层多条规则只显示一次且不改变时辰判断", () => {
    const 汇总 = 汇总当日风水状态([规则("月罗睺日", "月"), 规则("逐月杀风水师日", "月")]);
    const 时辰结果 = 判断全部时辰规则(配置, "子", "寅", 1);
    expect(汇总).toMatchObject({ 犯忌层级: ["月"], 当日状态: "日犯月忌" });
    expect(时辰结果).toHaveLength(3);
    expect(时辰结果.find((项目) => 项目.名称 === "杀师时")?.状态).toBe("未命中");
  });

  it("固定多条日级案例合并月日层级", () => {
    expect(计算日级风水禁忌(配置, 时刻(2025, 10, 26))).toMatchObject({
      犯忌层级: ["月", "日"],
      当日状态: "日犯月忌 · 阴阳宅禁日",
    });
  });

  it("正式汇总文案不再包含旧犯忌表达或当日不宜尾巴", () => {
    const 结果 = [
      汇总当日风水状态([规则("年罗睺日", "年")]).当日状态,
      汇总当日风水状态([规则("季罗睺日", "季")]).当日状态,
      汇总当日风水状态([规则("月罗睺日", "月")]).当日状态,
    ].join("|");
    expect(结果).not.toMatch(/(?:年|季|月)犯忌|当日不宜/u);
  });
});
