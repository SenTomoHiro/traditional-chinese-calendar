import { describe, expect, it } from "vitest";
import { 创建北京时间 } from "../src/历法";
import { 读取全部配置 } from "../src/规则/配置读取";
import { 执行择日, 计算已核日期事实, type 择日人物输入, type 现代事项 } from "../src/择日/择日";

const 配置 = 读取全部配置();
const 甲: 择日人物输入 = { 标签: "甲方", 日期: "1990-05-20", 时间: "14:35", 性别: "男", 时间依据: "北京时间", 经度: null };
const 乙: 择日人物输入 = { 标签: "乙方", 日期: "1992-09-12", 时间: "08:10", 性别: "女", 时间依据: "北京时间", 经度: null };
const 单日 = (事项: 现代事项, 日期: string, 人物: 择日人物输入[] = [甲]) => 执行择日(事项, 日期, 日期, 人物, "北京时间", null, 配置).候选[0];

describe("择日判例 D01—D25", () => {
  it("D01—D04 安床危日与三合月厌正反事实", () => {
    expect(单日("安床", "2026-08-09").公共日课[0].宜证据).toContain("危日");
    expect(单日("安床", "2026-08-10").公共日课[0].宜证据).not.toContain("危日");
    const 订婚正 = 单日("订婚", "2026-08-10");
    expect(订婚正.公共日课.every((项) => 项.宜证据.includes("三合"))).toBe(true);
    expect(订婚正.公共日课.every((项) => 项.忌证据.includes("月厌"))).toBe(true);
    expect(订婚正.公共日课.every((项) => 项.状态 === "原始宜忌并见")).toBe(true);
    expect(单日("订婚", "2026-08-09").公共日课.every((项) => !项.宜证据.includes("三合"))).toBe(true);
  });

  it("D05—D08 劫煞灾煞月煞逐日不混淆", () => {
    const 十一 = 单日("订婚", "2026-08-11").公共日课;
    expect(十一.some((项) => 项.宜证据.includes("六合"))).toBe(true);
    expect(十一.every((项) => !项.忌证据.includes("劫煞"))).toBe(true);
    expect(单日("订婚", "2026-08-12").公共日课.every((项) => !项.忌证据.includes("劫煞"))).toBe(true);
    expect(单日("开业", "2026-08-12").公共日课[0].忌证据).not.toContain("灾煞");
    expect(单日("开业", "2026-08-13").公共日课[0].忌证据).toContain("月煞");
  });

  it("D09 月破大耗同位不在证据中重复累计", () => {
    const 结论 = 单日("开业", "2026-09-26").公共日课[0];
    expect(结论.忌证据).toContain("月破");
    expect(结论.忌证据.filter((项) => ["月破", "大耗"].includes(项))).toHaveLength(1);
  });

  it("D10—D11 巳日出行专忌且卯日不触发", () => {
    expect(单日("出行", "2026-08-11").公共日课[0].忌证据).toContain("巳日");
    expect(单日("出行", "2026-08-09").公共日课[0].忌证据).not.toContain("巳日");
  });

  it("D12 月厌成日无指定德时保留冲突", () => {
    expect(单日("订婚", "2026-08-10").公共日课.every((项) => 项.状态 === "原始宜忌并见")).toBe(true);
  });

  it("D13 劫煞收日六合分支解除通例但保留巳日专忌", () => {
    expect(单日("订婚", "2026-08-11").公共日课.every((项) => !项.忌证据.includes("劫煞") && !项.忌证据.includes("收日"))).toBe(true);
    expect(单日("出行", "2026-08-11").公共日课[0].忌证据).toContain("巳日");
  });

  it("D14 灾煞开日与天德合分支不把九项按灾煞全忌", () => {
    const 结论 = 单日("祈福", "2026-08-12").公共日课[0];
    expect(结论.宜证据).toContain("开日");
    expect(结论.忌证据).not.toContain("灾煞");
  });

  it("D15 闭日月煞无德为诸事皆忌已裁断", () => {
    const 结论 = 单日("开业", "2026-08-13").公共日课[0];
    expect(结论.状态).toBe("已裁断");
    expect(结论.结论).toContain("诸事皆忌");
  });

  it("D16 破厌灾同位即使德合也走强分支", () => {
    const 结论 = 单日("结婚", "2026-09-26").公共日课[0];
    expect(结论.状态).toBe("已裁断");
    expect(结论.结论).toContain("诸事皆忌");
  });

  it("D17—D19 未闭环联动保留并见或待校而不猜终值", () => {
    expect(["原始宜忌并见", "资料未全"]).toContain(单日("搬家", "2026-08-10").公共日课[0].状态);
    expect(["原始宜忌并见", "资料未全"]).toContain(单日("开业", "2026-08-10").公共日课[0].状态);
    expect(["原始宜忌并见", "资料未全"]).toContain(单日("祈福", "2026-08-10").公共日课[0].状态);
  });

  it("D20—D21 四绝四离按民用日前一日命中", () => {
    expect(计算已核日期事实(创建北京时间(2026, 2, 3, 12)).四绝).toBe(true);
    expect(计算已核日期事实(创建北京时间(2026, 2, 4, 12)).四绝).toBe(false);
    expect(计算已核日期事实(创建北京时间(2026, 3, 19, 12)).四离).toBe(true);
    expect(计算已核日期事实(创建北京时间(2026, 3, 20, 12)).四离).toBe(false);
  });

  it("D22—D25 长星短星只按已核非闰农历月日格", () => {
    expect(计算已核日期事实(创建北京时间(2026, 2, 23, 12)).长星).toBe(true);
    expect(计算已核日期事实(创建北京时间(2026, 2, 24, 12)).长星).toBe(false);
    expect(计算已核日期事实(创建北京时间(2026, 9, 12, 12)).长星).toBe(true);
    expect(计算已核日期事实(创建北京时间(2026, 9, 28, 12)).短星).toBe(true);
  });
});

describe("个性化与择时", () => {
  it("单人关系分层且不输出分数或唯一喜用神", () => {
    const 结果 = 单日("签约", "2026-08-12");
    expect(结果.人物关系).toHaveLength(1);
    expect(结果.人物关系[0].项目.every((项) => ["严重不利", "需要注意", "有利关系", "辅助关系"].includes(项.层级))).toBe(true);
    expect(JSON.stringify(结果)).not.toMatch(/\d+分|喜用神/u);
  });

  it("双人逐方呈现并优先规避任一方严重冲突", () => {
    const 结果 = 单日("结婚", "2026-08-12", [甲, 乙]);
    expect(结果.人物关系.map((项) => 项.标签)).toEqual(["甲方", "乙方"]);
    expect(结果.共同结论).toBeTruthy();
    if (结果.人物关系.some((项) => 项.项目.some((关系) => 关系.层级 === "严重不利"))) expect(结果.推荐程度).toBe("不优先");
  });

  it("同日逐时重算并返回多个可解释时辰", () => {
    const 结果 = 单日("出行", "2026-08-09");
    expect(结果.推荐时辰).toHaveLength(3);
    expect(new Set(结果.推荐时辰.map((项) => 项.时柱)).size).toBeGreaterThan(1);
    expect(结果.推荐时辰.every((项) => 项.时间范围.includes("～"))).toBe(true);
  });

  it("入宅资料未全只阻止入宅自身终判", () => {
    const 结果 = 单日("搬家", "2026-08-09");
    expect(结果.公共日课.find((项) => 项.id === "入宅")?.状态).toBe("资料未全");
    expect(结果.公共日课.find((项) => 项.id === "移徙")?.状态).not.toBeUndefined();
  });
});
