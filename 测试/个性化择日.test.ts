describe("个性化与择时", () => {
  it("完整排序保留供审计，主推荐只取零至五个合格结果", () => {
    const 结果 = 执行择日("出行", "2026-08-01", "2026-08-31", [甲], "北京时间", null, 配置);
    expect(结果.候选).toHaveLength(31);
    expect(结果.推荐候选.length).toBeLessThanOrEqual(5);
    expect(结果.推荐候选).toEqual(
      结果.候选.filter((候选) => 候选.推荐程度 !== "不优先").slice(0, 5),
    );
    expect(结果.推荐候选.every((候选) => 候选.推荐程度 !== "不优先")).toBe(true);
  });

  it("短范围可少于两个主推荐且不会用次等结果凑数", () => {
    const 结果 = 执行择日("出行", "2026-08-11", "2026-08-11", [甲], "北京时间", null, 配置);
    expect(结果.推荐候选.length).toBeLessThan(2);
    expect(结果.候选).toHaveLength(1);
  });

  it("单人关系分层且不输出分数或唯一喜用神", () => {
    const 结果 = 单日("立券/签约", "2026-08-12");
    expect(结果.人物关系).toHaveLength(1);
    expect(结果.人物关系[0].项目.every((项) => ["严重不利", "需要注意", "有利关系", "辅助关系"].includes(项.层级))).toBe(true);
    expect(JSON.stringify(结果)).not.toMatch(/\d+分|喜用神/u);
  });

  it("双人逐方呈现并优先规避任一方严重冲突", () => {
    const 结果 = 单日("结婚", "2026-08-12", [甲, 乙]);
    expect(结果.人物关系.map((项) => 项.标签)).toEqual(["甲方", "乙方"]);
    expect(结果.共同结论).toBeTruthy();
    if (结果.人物关系.some((项) => 项.项目.some((关系) => 关系.层级 === "严重不利"))) {
      expect(["谨慎选择", "不优先"]).toContain(结果.推荐程度);
      expect(结果.共同结论).toContain("不冒充公共日课硬禁");
    }
  });

  it("同日逐时重算并返回多个可解释时辰", () => {
    const 结果 = 单日("出行", "2026-08-09");
    expect(结果.推荐时辰).toHaveLength(3);
    expect(new Set(结果.推荐时辰.map((项) => 项.时柱)).size).toBeGreaterThan(1);
    expect(结果.推荐时辰.every((项) => 项.时间范围.includes("～"))).toBe(true);
  });

  it("搬家默认只含移徙与入宅，安床和归火保持独立入口", () => {
    const 结果 = 单日("搬家", "2026-08-09");
    expect(结果.公共日课.map((项) => 项.id)).toEqual(["移徙", "入宅"]);
    expect(单日("搬家全套", "2026-08-09").公共日课.map((项) => 项.id)).toEqual(["移徙", "入宅", "安床", "归火"]);
    expect(单日("归火", "2026-08-09").公共日课[0].id).toBe("归火");
    expect(结果.公共日课.find((项) => 项.id === "入宅")?.结论).toContain("空间条件保持独立");
  });

  it("九项普通日期不因工程缺口返回资料未全", () => {
    const 事项们: 现代事项[] = ["订婚", "结婚", "搬家", "安床", "开市/开业", "立券/签约", "出行", "祈福"];
    for (const 事项 of 事项们) {
      const 结果 = 执行择日(事项, "2026-01-01", "2026-03-31", [甲], "北京时间", null, 配置);
      expect(结果.候选.flatMap((日) => 日.公共日课).some((项) => 项.状态 === "资料未全" || 项.铺注状态 === "资料未全"), 事项).toBe(false);
    }
  });

  it("闰月开市与立券按长短星终判，不再返回资料未全", () => {
    expect(单日("开市/开业", "2023-03-25").公共日课[0].忌证据).toContain("长星");
    expect(单日("立券/签约", "2025-08-15").公共日课[0].忌证据).toContain("短星");
    for (const [事项, 日期] of [["开市/开业", "2023-03-25"], ["立券/签约", "2025-08-15"]] as const) {
      const 结论 = 单日(事项, 日期).公共日课[0];
      expect(结论.状态).not.toBe("资料未全");
      expect(结论.铺注状态).not.toBe("资料未全");
      expect(结论.待校).toEqual([]);
    }
  });
});
