import { describe, expect, it } from "vitest";
import { 创建日期事件分栏 } from "../src/界面/详情布局";

describe("左侧详情紧凑分栏", () => {
  it("神圣纪念和传统节日都有时各自保留", () => {
    expect(创建日期事件分栏(["道德腊之辰"], ["七夕节"])).toEqual([
      { 标题: "神圣纪念", 事件: ["道德腊之辰"] },
      { 标题: "传统节日", 事件: ["七夕节"] },
    ]);
  });

  it("只有神圣纪念时仍维持双栏", () => {
    expect(创建日期事件分栏(["道德腊之辰"], [])).toHaveLength(2);
    expect(创建日期事件分栏(["道德腊之辰"], [])[1].事件).toEqual([]);
  });

  it("只有传统节日时仍维持双栏", () => {
    expect(创建日期事件分栏([], ["七夕节"])).toHaveLength(2);
    expect(创建日期事件分栏([], ["七夕节"])[0].事件).toEqual([]);
  });

  it("两者都没有时不生成空模块", () => {
    expect(创建日期事件分栏([], [])).toEqual([]);
  });
});
