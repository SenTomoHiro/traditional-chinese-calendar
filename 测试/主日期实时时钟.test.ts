import { describe, expect, it } from "vitest";
import { 创建实时查询时间, 创建手动查询时间 } from "../src/实时历时";
import { 创建北京时间 } from "../src/历法/时间";
import { 刷新主日期实时时钟 } from "../src/界面/主日期实时时钟";

describe("切换日期后的默认时辰", () => {
  it("历史和未来日期都使用当前真实时分而不是固定中午", () => {
    for (const 所选日期 of [new Date(1999, 11, 31), new Date(2099, 0, 1)]) {
      const 结果 = 刷新主日期实时时钟(
        所选日期,
        new Date(2026, 7, 10),
        创建实时查询时间(创建北京时间(2026, 8, 10, 15, 21)),
        创建北京时间(2026, 8, 10, 15, 22),
      );
      expect(结果.时间查询).toEqual({ 模式: "实时", 时间: "15:22" });
      expect(结果.所选日期).toBe(所选日期);
    }
  });

  it("固定查询日期跨现实午夜仍保持不变，只刷新真实时分", () => {
    const 固定日期 = new Date(2026, 7, 11);
    const 结果 = 刷新主日期实时时钟(
      固定日期,
      new Date(2026, 7, 10),
      创建实时查询时间(创建北京时间(2026, 8, 10, 23, 59)),
      创建北京时间(2026, 8, 11, 0, 0),
    );
    expect(结果.所选日期).toBe(固定日期);
    expect(结果.今天).toEqual(new Date(2026, 7, 11));
    expect(结果.时间查询.时间).toBe("00:00");
  });

  it("原本选择今天时跨现实午夜继续跟随新今天", () => {
    const 结果 = 刷新主日期实时时钟(
      new Date(2026, 7, 10),
      new Date(2026, 7, 10),
      创建实时查询时间(创建北京时间(2026, 8, 10, 23, 59)),
      创建北京时间(2026, 8, 11, 0, 0),
    );
    expect(结果.所选日期).toEqual(new Date(2026, 7, 11));
  });

  it("手动时间不会被分钟更新覆盖", () => {
    const 结果 = 刷新主日期实时时钟(
      new Date(2026, 7, 20),
      new Date(2026, 7, 10),
      创建手动查询时间("21:35"),
      创建北京时间(2026, 8, 10, 15, 22),
    );
    expect(结果.时间查询).toEqual({ 模式: "手动", 时间: "21:35" });
  });
});
