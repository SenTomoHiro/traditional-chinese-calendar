import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { 解析配置, type 配置解析结果 } from "../src/规则/配置读取";
import { 判断全部时辰规则 } from "../src/规则/时辰规则";

const 文件名列表 = ["杀师时.txt", "造葬杀风水师时.txt", "逐月杀风水师时.txt"];
const 全部配置: 配置解析结果[] = 文件名列表.map((文件名) =>
  解析配置(文件名, readFileSync(resolve(process.cwd(), "配置", 文件名), "utf8")),
);

function 规则(名称: string, 日支: Parameters<typeof 判断全部时辰规则>[1], 时支: Parameters<typeof 判断全部时辰规则>[2], 月 = 1) {
  return 判断全部时辰规则(全部配置, 日支, 时支, 月).find((结果) => 结果.名称 === 名称);
}

describe("现有三类时辰配置规则", () => {
  it("杀师时使用最终日支和时支判断命中", () => {
    expect(规则("杀师时", "子", "丑")).toMatchObject({ 状态: "命中", 说明: "子日 · 忌丑、午时 · 丑时命中" });
  });

  it("杀师时明确返回未命中", () => {
    expect(规则("杀师时", "子", "寅")).toMatchObject({ 状态: "未命中", 说明: "子日 · 忌丑、午时 · 寅时未命中" });
  });

  it("造葬杀风水师时使用独立配置判断命中", () => {
    expect(规则("造葬杀风水师时", "子", "卯")).toMatchObject({ 状态: "命中", 说明: "子日 · 忌丑、卯时 · 卯时命中" });
  });

  it("造葬杀风水师时明确返回未命中", () => {
    expect(规则("造葬杀风水师时", "子", "午")?.状态).toBe("未命中");
  });

  it("逐月规则使用最终农历月份和时支判断命中", () => {
    expect(规则("逐月杀风水师时", "子", "卯", 1)).toMatchObject({ 状态: "命中", 说明: "正月 · 忌卯时 · 卯时命中" });
  });

  it("逐月规则明确返回未命中", () => {
    expect(规则("逐月杀风水师时", "子", "辰", 1)?.状态).toBe("未命中");
  });

  it("农历十月的“无”是有效无规则状态", () => {
    expect(规则("逐月杀风水师时", "子", "子", 10)).toMatchObject({
      状态: "无规则",
      说明: "十月 · 无此规则",
    });
  });

  it("辰日与六月完整显示原规则规定的禁忌时辰", () => {
    expect(规则("杀师时", "辰", "酉")?.说明).toBe("辰日 · 忌巳、丑时 · 酉时未命中");
    expect(规则("杀师时", "辰", "巳")?.说明).toBe("辰日 · 忌巳、丑时 · 巳时命中");
    expect(规则("造葬杀风水师时", "辰", "酉")?.说明).toBe("辰日 · 忌子、戌时 · 酉时未命中");
    expect(规则("逐月杀风水师时", "辰", "酉", 6)?.说明).toBe("六月 · 忌寅时 · 酉时未命中");
  });

  it("缺失配置时明确报告配置错误", () => {
    expect(判断全部时辰规则([], "子", "丑", 1).every((结果) => 结果.状态 === "配置错误")).toBe(true);
  });

  it("实际三个配置文件都无解析错误", () => {
    expect(全部配置.every((配置) => 配置.错误.length === 0)).toBe(true);
  });
});
