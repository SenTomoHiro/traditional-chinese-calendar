import { describe, expect, it } from "vitest";
import { 计算当前历时 } from "../src/当前历时";
import { 创建北京时间, 解析日吉凶配置, 计算日吉凶, 计算日期详情 } from "../src/历法";
import { 读取全部配置 } from "../src/规则/配置读取";

const 时刻 = (年: number, 月: number, 日: number, 时 = 12, 分 = 0) => 创建北京时间(年, 月, 日, 时, 分);
const 吉神 = new Set(["青龙", "明堂", "金匮", "天德", "玉堂", "司命"]);
const 凶神 = new Set(["天刑", "朱雀", "白虎", "天牢", "玄武", "勾陈"]);

describe("十二天神日吉凶", () => {
  it("2026-08-09按卷七月内天黄道规则自主计算", () => {
    const 结果 = 计算日吉凶(时刻(2026, 8, 9));
    expect(结果).toEqual({ 天神: "朱雀", 类型: "黑道", 吉凶: "凶" });
  });

  it("中文配置完整覆盖十二节气月和十二天神", () => {
    const 配置 = 解析日吉凶配置();
    expect(Object.keys(配置.青龙起日)).toHaveLength(12);
    expect(配置.值神).toHaveLength(12);
    expect(配置.吉神.size).toBe(6);
  });

  it("连续十二日完整覆盖十二天神且六吉六凶分类正确", () => {
    const 结果 = Array.from({ length: 12 }, (_, 索引) => 计算日吉凶(时刻(2026, 8, 13 + 索引)));
    expect(new Set(结果.map((项目) => 项目.天神))).toEqual(new Set([...吉神, ...凶神]));
    expect(结果.filter((项目) => 项目.吉凶 === "吉").map((项目) => 项目.天神).sort()).toEqual([...吉神].sort());
    expect(结果.filter((项目) => 项目.吉凶 === "凶").map((项目) => 项目.天神).sort()).toEqual([...凶神].sort());
    expect(结果.every((项目) => 项目.类型 === (项目.吉凶 === "吉" ? "黄道" : "黑道"))).toBe(true);
  });

  it("日吉凶是独立十二天神结果，不与十二建星混算", () => {
    const 结果 = 计算日期详情(2026, 8, 9);
    expect(结果.值星).toBe("危");
    expect(结果.日吉凶).toEqual({ 天神: "朱雀", 类型: "黑道", 吉凶: "凶" });
  });

  it("23:30夜子仍用当日结果，00:30早子切换次日结果", () => {
    expect(计算日吉凶(时刻(2026, 8, 9, 23, 30))).toEqual(计算日吉凶(时刻(2026, 8, 9, 12)));
    expect(计算日吉凶(时刻(2026, 8, 10, 0, 30))).toEqual({ 天神: "金匮", 类型: "黄道", 吉凶: "吉" });
    expect(计算日吉凶(时刻(2026, 8, 10, 0, 30))).not.toEqual(计算日吉凶(时刻(2026, 8, 9, 23, 30)));
  });

  it("日期切换后立即刷新", () => {
    expect(计算日期详情(2026, 8, 9).日吉凶).not.toEqual(计算日期详情(2026, 8, 10).日吉凶);
  });

  it("真太阳时跨日时与最终日柱同步切换", () => {
    const 配置 = 读取全部配置();
    const 北京 = 计算当前历时(时刻(2026, 8, 9, 1), "北京时间", 60, 配置);
    const 真太阳 = 计算当前历时(时刻(2026, 8, 9, 1), "真太阳时", 60, 配置);
    expect(北京.最终.最终时间.日).toBe(9);
    expect(真太阳.最终.最终时间.日).toBe(8);
    expect(北京.历法结果.日吉凶).toEqual(计算日吉凶(北京.最终.最终时间));
    expect(真太阳.历法结果.日吉凶).toEqual(计算日吉凶(真太阳.最终.最终时间));
    expect(真太阳.历法结果.日吉凶).not.toEqual(北京.历法结果.日吉凶);
  });
});
