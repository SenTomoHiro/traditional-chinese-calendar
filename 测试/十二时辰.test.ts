import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { 创建北京时间 } from "../src/历法/时间";
import { 创建十二时辰概览, 反求北京时间 } from "../src/历法/十二时辰";
import { 计算真太阳时 } from "../src/历法/真太阳时";
import { 解析配置 } from "../src/规则/配置读取";
import { 解析时辰吉凶配置 } from "../src/规则/时辰吉凶";

const 时刻 = (年: number, 月: number, 日: number, 时 = 12, 分 = 0, 秒 = 0) => 创建北京时间(年, 月, 日, 时, 分, 秒);
const 配置文本 = readFileSync(resolve(process.cwd(), "配置", "时辰吉凶.txt"), "utf8");
const 配置 = 解析时辰吉凶配置(解析配置("时辰吉凶.txt", 配置文本)).配置;

function 毫秒(时间: ReturnType<typeof 时刻>): number {
  return Date.UTC(时间.年, 时间.月 - 1, 时间.日, 时间.时, 时间.分, 时间.秒);
}

describe("北京时间十二时辰概览", () => {
  const 概览 = 创建十二时辰概览(时刻(2026, 8, 10, 12, 30), "北京时间", null, 配置);

  it("保持十二个时辰且只在子时内部拆分夜子和早子", () => {
    expect(概览.项目).toHaveLength(12);
    expect(概览.项目[0]).toMatchObject({ 名称: "子时", 时支: "子" });
    expect(概览.项目[0].时段.map((段) => 段.名称)).toEqual(["夜子", "早子"]);
    expect(概览.项目.slice(1).every((项目) => 项目.时段.length === 1)).toBe(true);
  });

  it("标准北京时间范围完整且连续", () => {
    expect(概览.项目.flatMap((项目) => 项目.时段).map((段) => 段.时间范围)).toEqual([
      "23:00～23:59", "00:00～00:59", "01:00～02:59", "03:00～04:59", "05:00～06:59",
      "07:00～08:59", "09:00～10:59", "11:00～12:59", "13:00～14:59", "15:00～16:59",
      "17:00～18:59", "19:00～20:59", "21:00～22:59",
    ]);
  });

  it("每个时段都有时柱、值神和吉凶", () => {
    for (const 时段 of 概览.项目.flatMap((项目) => 项目.时段)) {
      expect(时段.时柱).toMatch(/^[甲乙丙丁戊己庚辛壬癸][子丑寅卯辰巳午未申酉戌亥]$/u);
      expect(时段.值神).not.toBe("配置错误");
      expect(["吉", "凶"]).toContain(时段.吉凶);
    }
  });

  it("夜子与早子分属午夜前后两个日柱并分别计算", () => {
    const [夜子, 早子] = 概览.项目[0].时段;
    expect(夜子).toMatchObject({ 时支: "子", 日柱: "乙卯", 时柱: "丙子", 值神: "司命", 吉凶: "吉" });
    expect(早子).toMatchObject({ 时支: "子", 日柱: "丙辰", 时柱: "戊子", 值神: "天牢", 吉凶: "凶" });
  });

  it("查询时间只高亮当前午时", () => {
    expect(概览.项目.filter((项目) => 项目.当前).map((项目) => 项目.时支)).toEqual(["午"]);
  });

  it("23:30高亮夜子，00:30高亮早子", () => {
    const 夜间 = 创建十二时辰概览(时刻(2026, 8, 9, 23, 30), "北京时间", null, 配置).项目[0];
    const 凌晨 = 创建十二时辰概览(时刻(2026, 8, 10, 0, 30), "北京时间", null, 配置).项目[0];
    expect(夜间.时段.map((段) => 段.当前)).toEqual([true, false]);
    expect(凌晨.时段.map((段) => 段.当前)).toEqual([false, true]);
    expect(夜间.时段.map((段) => 段.日柱)).toEqual(凌晨.时段.map((段) => 段.日柱));
  });
});

describe("真太阳时十二时辰边界反求", () => {
  it("反求结果复用现有算法并命中真太阳时边界", () => {
    const 目标 = 时刻(2026, 8, 10, 0, 0);
    const 北京 = 反求北京时间(目标, 116.4);
    const 回算 = 计算真太阳时(北京, 116.4).真太阳时;
    expect(Math.abs(毫秒(回算) - 毫秒(目标))).toBeLessThanOrEqual(1000);
  });

  it("真太阳时范围显示分钟偏移且全部精确到分钟", () => {
    const 概览 = 创建十二时辰概览(时刻(2026, 8, 10, 12), "真太阳时", 116.4, 配置);
    const 范围 = 概览.项目.flatMap((项目) => 项目.时段).map((段) => 段.时间范围);
    expect(范围[0]).not.toBe("23:00～23:59");
    expect(范围.every((文本) => /^\d{2}:\d{2}～\d{2}:\d{2}$/u.test(文本))).toBe(true);
  });

  it("东于120度的边界提前，西于120度的边界延后", () => {
    const 目标 = 时刻(2026, 8, 10, 0);
    expect(毫秒(反求北京时间(目标, 121.5))).toBeLessThan(毫秒(反求北京时间(目标, 120)));
    expect(毫秒(反求北京时间(目标, 116.4))).toBeGreaterThan(毫秒(反求北京时间(目标, 120)));
  });

  it("不同日期因均时差得到不同边界", () => {
    const 冬季 = 反求北京时间(时刻(2026, 2, 11, 0), 120);
    const 秋季 = 反求北京时间(时刻(2026, 11, 3, 0), 120);
    expect(`${冬季.时}:${冬季.分}`).not.toBe(`${秋季.时}:${秋季.分}`);
  });

  it("真太阳时23点和0点分别作为夜子与早子起点", () => {
    const 概览 = 创建十二时辰概览(时刻(2026, 8, 10, 0), "真太阳时", 116.4, 配置);
    const [夜子, 早子] = 概览.项目[0].时段;
    const 夜子目标 = 时刻(2026, 8, 9, 23);
    const 早子目标 = 时刻(2026, 8, 10, 0);
    expect(Math.abs(毫秒(计算真太阳时(夜子.开始北京时间, 116.4).真太阳时) - 毫秒(夜子目标))).toBeLessThanOrEqual(30_000);
    expect(Math.abs(毫秒(计算真太阳时(早子.开始北京时间, 116.4).真太阳时) - 毫秒(早子目标))).toBeLessThanOrEqual(30_000);
    expect(夜子.日柱).not.toBe(早子.日柱);
  });

  it("真太阳时当前时辰按换算后的边界高亮", () => {
    const 查询 = 反求北京时间(时刻(2026, 8, 10, 11, 30), 116.4);
    const 概览 = 创建十二时辰概览(查询, "真太阳时", 116.4, 配置);
    expect(概览.项目.filter((项目) => 项目.当前).map((项目) => 项目.时支)).toEqual(["午"]);
  });
});
