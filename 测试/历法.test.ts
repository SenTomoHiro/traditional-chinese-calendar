const 时刻 = (年: number, 月: number, 日: number, 时 = 12, 分 = 0, 秒 = 0) =>
  创建北京时间(年, 月, 日, 时, 分, 秒);

// 农历日期与交节分钟交叉校验来源：香港天文台 2024—2026 公农历对照表及 2026 年历。
// https://www.hko.gov.hk/sc/gts/time/conversion.htm
// https://www.hko.gov.hk/sc/gts/astron2026/almanac2026_index.htm

describe("2026-08-09 固定回归案例", () => {
  it("一次计算得到全部指定结果", () => {
    const 结果 = 计算日期详情(2026, 8, 9);
    expect(结果.农历.显示).toBe("六月廿七");
    expect(结果.农历.是否闰月).toBe(false);
    expect(结果.年柱).toBe("丙午");
    expect(结果.月柱).toBe("丙申");
    expect(结果.日柱).toBe("乙卯");
    expect(结果.月建).toBe("申");
    expect(结果.值星).toBe("危");
    expect(结果.时柱).toBeNull();
  });
});

describe("中国农历转换", () => {
  it("识别 2024 年正月初一", () => {
    expect(转换为农历(时刻(2024, 2, 10))).toMatchObject({
      年: 2024,
      月: 1,
      日: 1,
      是否闰月: false,
      显示: "正月初一",
    });
  });

  it("识别农历小月月末", () => {
    expect(转换为农历(时刻(2024, 3, 9))).toMatchObject({ 月: 1, 日: 29, 显示: "正月廿九" });
  });

  it("识别农历大月三十", () => {
    expect(转换为农历(时刻(2024, 4, 8))).toMatchObject({ 月: 2, 日: 30, 显示: "二月三十" });
  });

  it("正常六月与闰六月严格分开", () => {
    const 正常六月 = 转换为农历(时刻(2025, 6, 25));
    const 闰六月 = 转换为农历(时刻(2025, 7, 25));
    expect(正常六月).toMatchObject({ 月: 6, 日: 1, 是否闰月: false, 显示: "六月初一" });
    expect(闰六月).toMatchObject({ 月: 6, 日: 1, 是否闰月: true, 显示: "闰六月初一" });
  });

  it("识别闰月月末", () => {
    expect(转换为农历(时刻(2025, 8, 22))).toMatchObject({
      月: 6,
      日: 29,
      是否闰月: true,
      显示: "闰六月廿九",
    });
  });

  it("闰月结束后进入下一个正常月份", () => {
    expect(转换为农历(时刻(2025, 8, 23))).toMatchObject({
      月: 7,
      日: 1,
      是否闰月: false,
      显示: "七月初一",
    });
  });

  it("公历跨年不会错误切换农历年", () => {
    expect(转换为农历(时刻(2026, 1, 1))).toMatchObject({ 年: 2025, 月: 11, 日: 13 });
  });

  it("农历年末到正月初一连续转换", () => {
    expect(转换为农历(时刻(2025, 1, 28))).toMatchObject({ 年: 2024, 月: 12, 日: 29 });
    expect(转换为农历(时刻(2025, 1, 29))).toMatchObject({ 年: 2025, 月: 1, 日: 1 });
  });
});

describe("二十四节气", () => {
  it("每年返回完整且不重复的 24 个节气", () => {
    const 全年 = 获取年度节气(2026);
    expect(全年).toHaveLength(24);
    expect(new Set(全年.map((节气) => 节气.名称))).toEqual(new Set(二十四节气名称));
  });

  it("节气按交节时刻先后排列", () => {
    expect(获取年度节气(2026).map((节气) => 节气.名称)).toEqual(二十四节气名称);
  });

  it("2026 年立春时刻与官方年历分钟一致", () => {
    const 立春 = 获取指定节气(2026, "立春");
    expect(立春).toMatchObject({ 年: 2026, 月: 2, 日: 4, 时: 4, 分: 2 });
  });

  it("2026 年立秋时刻四舍五入到官方年历的 19:43", () => {
    const 立秋 = 获取指定节气(2026, "立秋");
    expect(立秋).toMatchObject({ 年: 2026, 月: 8, 日: 7, 时: 19 });
    expect(Math.round(立秋.分 + 立秋.秒 / 60)).toBe(43);
  });

  it("节气日返回名称和具体时刻", () => {
    expect(获取当日节气(时刻(2026, 8, 7))).toMatchObject({ 名称: "立秋", 时: 19, 分: 42 });
  });

  it("普通日期明确没有节气", () => {
    expect(获取当日节气(时刻(2026, 8, 9))).toBeNull();
  });

  it("小寒前后切换节气月", () => {
    expect(获取节气月(时刻(2026, 1, 5, 16, 22)).月建).toBe("子");
    expect(获取节气月(时刻(2026, 1, 5, 16, 24)).月建).toBe("丑");
  });

  it("惊蛰前后切换节气月", () => {
    expect(获取节气月(时刻(2026, 3, 5, 21, 58)).月建).toBe("寅");
    expect(获取节气月(时刻(2026, 3, 5, 22, 0)).月建).toBe("卯");
  });

  it("立秋前后切换节气月", () => {
    expect(获取节气月(时刻(2026, 8, 7, 19, 41)).月建).toBe("未");
    expect(获取节气月(时刻(2026, 8, 7, 19, 44)).月建).toBe("申");
  });
});

describe("年柱按立春具体时刻换年", () => {
  it("立春前一分钟仍属上一干支年", () => {
    expect(计算年柱(时刻(2026, 2, 4, 4, 1))).toBe("乙巳");
  });

  it("立春后一分钟进入新干支年", () => {
    expect(计算年柱(时刻(2026, 2, 4, 4, 3))).toBe("丙午");
  });

  it("日期详情采用中午基准，因此立春日显示新年柱", () => {
    expect(计算日期详情(2026, 2, 4).年柱).toBe("丙午");
  });
});

describe("月柱按节气月与五虎遁计算", () => {
  it("2026-08-09 是丙申月而非按农历六月取月", () => {
    const 结果 = 计算日期详情(2026, 8, 9);
    expect(结果.农历.月).toBe(6);
    expect(结果.月建).toBe("申");
    expect(结果.月柱).toBe("丙申");
  });

  it("立春交节前后由丑月切到寅月", () => {
    expect(计算月柱(时刻(2026, 2, 4, 4, 1))).toEqual({ 月柱: "己丑", 月建: "丑" });
    expect(计算月柱(时刻(2026, 2, 4, 4, 3))).toEqual({ 月柱: "庚寅", 月建: "寅" });
  });

  it("惊蛰交节前后由庚寅切到辛卯", () => {
    expect(计算月柱(时刻(2026, 3, 5, 21, 58))).toEqual({ 月柱: "庚寅", 月建: "寅" });
    expect(计算月柱(时刻(2026, 3, 5, 22, 0))).toEqual({ 月柱: "辛卯", 月建: "卯" });
  });

  it("立秋交节前后由乙未切到丙申", () => {
    expect(计算月柱(时刻(2026, 8, 7, 19, 41))).toEqual({ 月柱: "乙未", 月建: "未" });
    expect(计算月柱(时刻(2026, 8, 7, 19, 44))).toEqual({ 月柱: "丙申", 月建: "申" });
  });

  it("小寒交节前后由戊子切到己丑", () => {
    expect(计算月柱(时刻(2026, 1, 5, 16, 22))).toEqual({ 月柱: "戊子", 月建: "子" });
    expect(计算月柱(时刻(2026, 1, 5, 16, 24))).toEqual({ 月柱: "己丑", 月建: "丑" });
  });
});

describe("统一日柱以子时开始的 23:00 换日", () => {
  it("固定日期 2026-08-09 为乙卯日", () => {
    expect(计算日柱(时刻(2026, 8, 9))).toEqual({ 日柱: "乙卯", 日支: "卯" });
  });

  it("22:59 仍属于旧日，23:00 准时进入新日", () => {
    expect(计算日柱(时刻(2026, 8, 9, 22, 59, 59))).toEqual({ 日柱: "乙卯", 日支: "卯" });
    expect(计算日柱(时刻(2026, 8, 9, 23, 0, 0))).toEqual({ 日柱: "丙辰", 日支: "辰" });
  });

  it("23:30 与次日 00:30 属于同一个新日柱", () => {
    expect(计算日柱(时刻(2026, 8, 9, 23, 30))).toEqual({ 日柱: "丙辰", 日支: "辰" });
    expect(计算日柱(时刻(2026, 8, 10, 0, 30))).toEqual({ 日柱: "丙辰", 日支: "辰" });
  });

  it("具体时刻的完整历法结果读取同一个权威日柱", () => {
    expect(计算历法(时刻(2026, 8, 9, 22, 59)).日柱).toBe("乙卯");
    expect(计算历法(时刻(2026, 8, 9, 23, 0)).日柱).toBe("丙辰");
  });
});

describe("十二值星", () => {
  it("申月从申日起按建除十二值星顺排", () => {
    const 预期 = ["建", "除", "满", "平", "定", "执", "破", "危", "成", "收", "开", "闭"];
    const 申位置 = 地支.indexOf("申");
    const 实际 = Array.from({ length: 12 }, (_, 偏移) => 计算值星("申", 地支[(申位置 + 偏移) % 12]));
    expect(实际).toEqual(预期);
  });

  it("申月卯日是危日", () => {
    expect(计算值星("申", "卯")).toBe("危");
  });

  it("固定案例通过统一月建与日支得到危日", () => {
    expect(计算日期详情(2026, 8, 9).值星).toBe("危");
  });
});
