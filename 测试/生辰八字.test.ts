import { describe, expect, it } from "vitest";
import { 八字支持范围, 查询生辰八字, 计算生辰八字 } from "../src/生辰八字";
import { 计算当前历时 } from "../src/当前历时";
import { 创建北京时间 } from "../src/历法/时间";
import { 读取全部配置 } from "../src/规则/配置读取";

const 时刻 = (年: number, 月: number, 日: number, 时: number, 分: number) => 创建北京时间(年, 月, 日, 时, 分);

describe("生辰八字统一四柱查询", () => {
  it("普通北京时间得到完整四柱", () => {
    expect(计算生辰八字(时刻(2026, 8, 9, 12, 0), "北京时间", null)).toMatchObject({
      年柱: "丙午", 月柱: "丙申", 日柱: "乙卯", 时柱: "壬午",
      八字: "丙午　丙申　乙卯　壬午",
    });
  });

  it("立春前后一分钟切换年柱", () => {
    expect(计算生辰八字(时刻(2026, 2, 4, 4, 1), "北京时间", null).年柱).toBe("乙巳");
    expect(计算生辰八字(时刻(2026, 2, 4, 4, 3), "北京时间", null).年柱).toBe("丙午");
  });

  it("惊蛰前后一分钟切换月柱", () => {
    expect(计算生辰八字(时刻(2026, 3, 5, 21, 58), "北京时间", null).月柱).toBe("庚寅");
    expect(计算生辰八字(时刻(2026, 3, 5, 22, 0), "北京时间", null).月柱).toBe("辛卯");
  });

  it("23点30分为当天夜子", () => {
    expect(计算生辰八字(时刻(2026, 8, 9, 23, 30), "北京时间", null)).toMatchObject({ 日柱: "乙卯", 时柱: "丙子" });
  });

  it("次日00点30分为次日早子", () => {
    expect(计算生辰八字(时刻(2026, 8, 10, 0, 30), "北京时间", null)).toMatchObject({ 日柱: "丙辰", 时柱: "戊子" });
  });

  it("日柱严格在00点切换", () => {
    const 午夜前 = 计算生辰八字(时刻(2026, 8, 9, 23, 59), "北京时间", null);
    const 午夜后 = 计算生辰八字(时刻(2026, 8, 10, 0, 0), "北京时间", null);
    expect(午夜前.日柱).toBe("乙卯");
    expect(午夜后.日柱).toBe("丙辰");
  });

  it("真太阳时按手工经度修正", () => {
    const 结果 = 计算生辰八字(时刻(2026, 8, 9, 12, 0), "真太阳时", 116.4);
    expect(结果.最终时间).toMatchObject({ 年: 2026, 月: 8, 日: 9, 时: 11, 分: 39 });
    expect(结果.经度).toBe(116.4);
  });

  it("真太阳时跨日后统一改变日柱", () => {
    const 北京 = 计算生辰八字(时刻(2026, 8, 9, 1, 0), "北京时间", null);
    const 真太阳 = 计算生辰八字(时刻(2026, 8, 9, 1, 0), "真太阳时", 60);
    expect(真太阳.最终时间).toMatchObject({ 年: 2026, 月: 8, 日: 8 });
    expect(真太阳.日柱).not.toBe(北京.日柱);
  });

  it("与主页面统一计算结果完全一致", () => {
    const 输入 = 时刻(2026, 8, 9, 23, 30);
    const 八字 = 计算生辰八字(输入, "真太阳时", 116.4);
    const 主页面 = 计算当前历时(输入, "真太阳时", 116.4, 读取全部配置());
    expect(八字.四柱).toBe(主页面.四柱);
  });

  it("真太阳时缺少经度时给出明确提示", () => {
    expect(查询生辰八字("1990-05-20", "14:35", "真太阳时", null)).toEqual({
      成功: false,
      提示: "请输入出生地经度，或使用当前定位",
    });
  });

  it("日期或时间尚未输入完整时只提示继续输入", () => {
    expect(查询生辰八字("19", "14:35", "北京时间", null)).toEqual({
      成功: false,
      提示: "请继续输入完整的公历日期和时间",
    });
    expect(查询生辰八字("1990-05-20", "1", "北京时间", null)).toEqual({
      成功: false,
      提示: "请继续输入完整的公历日期和时间",
    });
  });

  it("完整但无效的公历日期不会计算", () => {
    expect(查询生辰八字("2026-02-31", "12:00", "北京时间", null)).toEqual({
      成功: false,
      提示: "请输入有效的公历日期和时间",
    });
  });

  it("超出已验证范围时友好处理", () => {
    expect(查询生辰八字("1899-12-31", "12:00", "北京时间", null)).toEqual({
      成功: false,
      提示: `当前历法计算支持范围为 ${八字支持范围.最小日期} 至 ${八字支持范围.最大日期}`,
    });
  });

  it("已验证范围两端都能正常计算", () => {
    expect(查询生辰八字(八字支持范围.最小日期, "12:00", "北京时间", null).成功).toBe(true);
    expect(查询生辰八字(八字支持范围.最大日期, "12:00", "北京时间", null).成功).toBe(true);
  });
});
