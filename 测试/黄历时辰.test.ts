describe("低层黄历时辰宜忌兼容", () => {
  it("当前依赖公开低层API存在", () => {
    expect(typeof LunarUtil.getTimeYi).toBe("function");
    expect(typeof LunarUtil.getTimeJi).toBe("function");
  });

  it("2026-08-09乙卯日十二时全部与参考核心宜忌一致", () => {
    expect(乙卯日预期).toHaveLength(12);
    for (const [索引, 时支] of 地支.entries()) {
      const 时柱 = 计算时柱("乙卯", 时支);
      const 结果 = 获取黄历时辰宜忌("乙卯", 时柱);
      expect({ 时柱, 宜: 结果.时宜, 忌: 结果.时忌 }, `${时支}时`).toEqual(乙卯日预期[索引]);
    }
  });

  it("真正空值会去掉库内无字占位", () => {
    expect(获取黄历时辰宜忌("乙卯", "乙酉")).toMatchObject({ 时宜: [], 时忌: ["诸事不宜"] });
  });

  it("夜子和早子只使用项目传入的不同日柱时柱", () => {
    const 夜子 = 获取黄历时辰宜忌("乙卯", "丙子");
    const 早子 = 获取黄历时辰宜忌("丙辰", "戊子");
    expect(夜子).not.toEqual(早子);
    expect(夜子.依据).toContain("本项目日柱、时柱");
  });

  it("北京时间与真太阳时切换后详情随统一四柱刷新", () => {
    const 配置 = 读取全部配置();
    const 输入 = 创建北京时间(2026, 8, 9, 1, 0);
    const 北京 = 计算当前历时(输入, "北京时间", 60, 配置);
    const 真太阳 = 计算当前历时(输入, "真太阳时", 60, 配置);
    const 北京当前段 = 北京.十二时辰.项目.flatMap((项) => 项.时段).find((段) => 段.当前);
    const 真太阳当前段 = 真太阳.十二时辰.项目.flatMap((项) => 项.时段).find((段) => 段.当前);
    expect(北京当前段?.日柱).not.toBe(真太阳当前段?.日柱);
    expect(北京当前段?.详情.时宜).not.toEqual(真太阳当前段?.详情.时宜);
  });
});
