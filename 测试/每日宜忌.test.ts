import { Solar } from "lunar-typescript";
import { describe, expect, it } from "vitest";
import { 计算当前历时 } from "../src/当前历时";
import {
  创建北京时间,
  平移时间,
  每日宜忌节气口径,
  获取指定节气,
  计算日期详情,
  计算日吉凶,
  计算每日宜忌,
} from "../src/历法";
import { 读取全部配置 } from "../src/规则/配置读取";

const 时刻 = (年: number, 月: number, 日: number, 时 = 12, 分 = 0) => 创建北京时间(年, 月, 日, 时, 分);

function 官方每日宜忌(时间: ReturnType<typeof 时刻>, 口径: 1 | 2 = 2) {
  const 农历 = Solar.fromYmdHms(时间.年, 时间.月, 时间.日, 时间.时, 时间.分, 时间.秒).getLunar();
  return { 宜: 农历.getDayYi(口径), 忌: 农历.getDayJi(口径) };
}

describe("每日宜忌", () => {
  it("固定采用节气精确口径并与2026-08-09官方结果一致", () => {
    expect(每日宜忌节气口径).toBe(2);
    expect(计算每日宜忌(时刻(2026, 8, 9))).toEqual(官方每日宜忌(时刻(2026, 8, 9), 2));
    expect(计算每日宜忌(时刻(2026, 8, 9))).toEqual({
      宜: ["祭祀", "入殓", "移柩", "结网", "启钻", "安葬", "除服", "成服", "馀事勿取"],
      忌: ["诸事不宜"],
    });
  });

  it("日期切换会立即刷新完整宜忌", () => {
    const 当日 = 计算日期详情(2026, 8, 9).每日宜忌;
    const 次日 = 计算日期详情(2026, 8, 10).每日宜忌;
    expect(当日).not.toEqual(次日);
    expect(次日).toEqual(官方每日宜忌(时刻(2026, 8, 10), 2));
  });

  it("23:30夜子仍用当日，00:30早子切换次日", () => {
    const 夜子 = 计算每日宜忌(时刻(2026, 8, 9, 23, 30));
    const 当日 = 计算每日宜忌(时刻(2026, 8, 9, 12));
    const 早子 = 计算每日宜忌(时刻(2026, 8, 10, 0, 30));
    expect(夜子).toEqual(当日);
    expect(早子).toEqual(官方每日宜忌(时刻(2026, 8, 10, 0, 30), 2));
    expect(早子).not.toEqual(夜子);
  });

  it("真太阳时跨日时与最终日期同步切换", () => {
    const 配置 = 读取全部配置();
    const 输入 = 时刻(2026, 8, 9, 1);
    const 北京 = 计算当前历时(输入, "北京时间", 60, 配置);
    const 真太阳 = 计算当前历时(输入, "真太阳时", 60, 配置);
    expect(北京.最终.最终时间.日).toBe(9);
    expect(真太阳.最终.最终时间.日).toBe(8);
    expect(北京.历法结果.每日宜忌).toEqual(计算每日宜忌(北京.最终.最终时间));
    expect(真太阳.历法结果.每日宜忌).toEqual(计算每日宜忌(真太阳.最终.最终时间));
    expect(真太阳.历法结果.每日宜忌).not.toEqual(北京.历法结果.每日宜忌);
  });

  it("每日宜忌与古籍日吉凶保持独立，不因凶日清空日宜", () => {
    expect(计算日吉凶(时刻(2026, 8, 9))).toEqual({ 天神: "朱雀", 类型: "黑道", 吉凶: "凶" });
    expect(计算每日宜忌(时刻(2026, 8, 9)).宜.length).toBeGreaterThan(0);
  });

  it.each(["立春", "惊蛰", "立秋", "白露"] as const)("%s前后严格按交节时刻切换口径", (名称) => {
    const 交节 = 获取指定节气(2026, 名称);
    const 交节前 = 平移时间(交节, -60);
    const 交节后 = 平移时间(交节, 60);
    const 前结果 = 计算每日宜忌(交节前);
    const 后结果 = 计算每日宜忌(交节后);
    expect(前结果).toEqual(官方每日宜忌(交节前, 2));
    expect(后结果).toEqual(官方每日宜忌(交节后, 2));
    expect(前结果).not.toEqual(后结果);
    expect(前结果).not.toEqual(官方每日宜忌(交节前, 1));
  });
});
